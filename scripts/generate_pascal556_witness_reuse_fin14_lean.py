def semantic_strong_five_lemma(original_id: int, literals: tuple[int, ...],
                                reverse_names: dict[int, str]) -> list[str]:
    strong5_literals = [x for x in literals if reverse_names[abs(x)].startswith("strong5.")]
    strong4_literals = [x for x in literals if reverse_names[abs(x)].startswith("strong4.")]
    if len(strong5_literals) != 1:
        raise ValueError(f"strong-five clause {original_id} has wrong output atom")
    output = strong5_literals[0]
    if output < 0:
        if len(strong4_literals) != 1 or strong4_literals[0] < 0:
            raise ValueError(f"strong-five forward clause {original_id} has wrong input")
        five = tuple(map(int, reverse_names[-output].split(".")[1:]))
        quad = tuple(map(int, reverse_names[strong4_literals[0]].split(".")[1:]))
        quads = tuple(__import__("itertools").combinations(five, 4))
        index = quads.index(quad)
        projection = ".".join(["2"] * index + ["1"]) if index < 4 else ".".join(["2"] * 4)
        body = [
            "  rintro ⟨hs, hnot⟩",
            "  apply hnot",
            f"  exact hs.{projection}",
        ]
    else:
        if len(strong4_literals) != 5 or any(x > 0 for x in strong4_literals):
            raise ValueError(f"strong-five reverse clause {original_id} has wrong inputs")
        body = [
            "  rintro ⟨hnot, h0, h1, h2, h3, h4⟩",
            "  apply hnot",
            "  exact ⟨h0, h1, h2, h3, h4⟩",
        ]
    return [
        f"theorem pascal556WitnessReuseFin14_clause{original_id:06d}_valid",
        "    (χ : TripleColoring 14) (cut : Fin 8) :",
        f"    ¬({semantic_failure(literals, reverse_names)}) := by",
        *body,
        "",
    ]


def no_five_color_hypotheses(vertices: tuple[int, ...], color: str) -> list[str]:
    names = []
    for triple in __import__("itertools").combinations(vertices, 3):
        names.append(f"({color_term(triple)} = Turn.{color})")
    return names


def semantic_no_five_lemma(original_id: int, category: str,
                            literals: tuple[int, ...], reverse_names: dict[int, str]) -> list[str]:
    five = clause_vertices(literals, reverse_names, "color")
    if len(five) != 5:
        raise ValueError(f"five-target clause {original_id} has no unique five-set")
    a, b, c, d, e = five
    is_cap = category == "no_cap_five"
    target = "Cap" if is_cap else "Cup"
    color = "right" if is_cap else "left"
    no_name = "hnoCap" if is_cap else "hnoCup"
    facts = [f"h{i}" for i in range(10)]
    lines = [
        f"theorem pascal556WitnessReuseFin14_clause{original_id:06d}_valid",
        "    (χ : TripleColoring 14) (cut : Fin 8)",
        f"    ({no_name} : ¬Contains{target}Set χ Finset.univ 5) :",
        f"    ¬({semantic_failure(literals, reverse_names)}) := by",
        f"  rintro ⟨{', '.join(facts)}⟩",
    ]
    if is_cap:
        triples = tuple(__import__("itertools").combinations(five, 3))
        for index, triple in enumerate(triples):
            lines += [
                f"  have hc{index} : {color_term(triple)} = Turn.right := by",
                f"    cases hcolor : {color_term(triple)} <;>",
                "      simp_all [Pascal556WitnessReuseFin14ColorAtom]",
            ]
        used_facts = [f"hc{i}" for i in range(10)]
    else:
        used_facts = facts
    lines += [
        f"  apply {no_name}",
        f"  refine ⟨{{{a}, {b}, {c}, {d}, {e}}}, by simp, by decide, ?_⟩",
        f"  apply pascal556WitnessReuseFin14_is{target}Set_five_of_colors χ",
        f"    {a} {b} {c} {d} {e} (by decide) (by decide) (by decide) (by decide)",
    ]
    if not is_cap:
        lines.append("  all_goals simpa only [Pascal556WitnessReuseFin14ColorAtom] using " + used_facts[0])
        # Replace the repeated one-goal line with explicit exact lines below.
        lines.pop()
    for fact in used_facts:
        if is_cap:
            lines.append(f"  · exact {fact}")
        else:
            lines.append(f"  · simpa only [Pascal556WitnessReuseFin14ColorAtom] using {fact}")
    lines.append("")
    return lines


