def semantic_side_no_cap_lemma(original_id: int, literals: tuple[int, ...],
                                reverse_names: dict[int, str]) -> list[str]:
    quad = clause_vertices(literals, reverse_names, "color")
    if len(quad) != 4:
        raise ValueError(f"side-cap clause {original_id} has no unique quad")
    cut_literals = [x for x in literals if reverse_names[abs(x)].startswith("cut.")]
    if len(cut_literals) != 1 or cut_literals[0] >= 0:
        raise ValueError(f"side-cap clause {original_id} has wrong cut literal")
    cut_value = int(reverse_names[abs(cut_literals[0])].split(".")[1])
    if all(v < cut_value for v in quad):
        side = "Left"
        no_name = "hnoLeft"
    elif all(cut_value <= v for v in quad):
        side = "Right"
        no_name = "hnoRight"
    else:
        raise ValueError(f"side-cap clause {original_id} crosses its cut")
    a, b, c, d = quad
    facts = [f"h{i}" for i in range(4)]
    triples = tuple(__import__("itertools").combinations(quad, 3))
    lines = [
        f"theorem pascal556WitnessReuseFin14_clause{original_id:06d}_valid",
        "    (χ : TripleColoring 14) (cut : Fin 8)",
        f"    ({no_name} : ¬ContainsCapSet χ (Pascal556WitnessReuseFin14Cut{side} cut) 4) :",
        f"    ¬({semantic_failure(literals, reverse_names)}) := by",
        f"  rintro ⟨hcut, {', '.join(facts)}⟩",
    ]
    for index, triple in enumerate(triples):
        lines += [
            f"  have hc{index} : {color_term(triple)} = Turn.right := by",
            f"    cases hcolor : {color_term(triple)} <;>",
            "      simp_all [Pascal556WitnessReuseFin14ColorAtom]",
        ]
    lines += [
        f"  apply {no_name}",
        f"  refine ⟨{{{a}, {b}, {c}, {d}}}, ?_, by decide, ?_⟩",
        "  · intro x hx",
        "    simp only [Finset.mem_insert, Finset.mem_singleton] at hx",
        "    rcases hx with rfl | rfl | rfl | rfl <;>",
        f"      simp [Pascal556WitnessReuseFin14Cut{side}, hcut]",
        "  · exact pascal556WitnessReuseFin14_isCapSet_four_of_colors χ",
        f"      {a} {b} {c} {d} (by decide) (by decide) (by decide)",
        "      hc0 hc1 hc2 hc3",
        "",
    ]
    return lines


def semantic_clause_lemma(original_id: int, category: str,
                           literals: tuple[int, ...], reverse_names: dict[int, str]) -> list[str]:
    if category == "one_change":
        return semantic_one_change_lemma(original_id, literals, reverse_names)
    if category == "strong_quad_iff":
        return semantic_strong_quad_lemma(original_id, literals, reverse_names)
    if category == "strong_five_iff":
        return semantic_strong_five_lemma(original_id, literals, reverse_names)
    if category in {"no_cap_five", "no_cup_five"}:
        return semantic_no_five_lemma(original_id, category, literals, reverse_names)
    if category == "no_strong_six":
        return semantic_no_strong_six_lemma(original_id, literals, reverse_names)
    if category == "cut_exactly_one":
        return semantic_cut_lemma(original_id, literals, reverse_names)
    if category == "side_no_cap_four":
        return semantic_side_no_cap_lemma(original_id, literals, reverse_names)
    raise ValueError(f"semantic clause category not implemented yet: {category}")


def generate_semantic_chunk(args: argparse.Namespace) -> None:
    if args.semantic_builder is None or args.semantic_map is None:
        raise ValueError("semantic generation requires --semantic-builder and --semantic-map")
    variable_count, core_clauses = parse_dimacs(args.cnf)
    origin_ids = tuple(int(text) for text in args.semantic_origin.read_text().split())
    if len(origin_ids) != len(core_clauses):
        raise ValueError("semantic origin list and core CNF differ in length")
    mapping = json.loads(args.semantic_map.read_text())
    if variable_count != mapping["variables"]:
        raise ValueError("semantic variable count differs from frozen map")
    reverse_names = {value: name for name, value in mapping["variable_map"].items()}
    formula, categories = load_frozen_formula(args.semantic_builder)
    if formula.names != mapping["variable_map"]:
        raise ValueError("reconstructed variable map differs from frozen map")
    frozen_cnf = args.semantic_builder / "formula.cnf"
    digest = hashlib.sha256(frozen_cnf.read_bytes()).hexdigest()
    if digest != mapping["cnf_sha256"]:
        raise ValueError("frozen formula hash differs from frozen map")
    for core_index, (origin_id, clause) in enumerate(zip(origin_ids, core_clauses)):
        if formula.clauses[origin_id - 1] != clause:
            raise ValueError(f"core clause {core_index} differs from origin {origin_id}")
    start = args.semantic_chunk_index * args.semantic_chunk_size
    stop = min(start + args.semantic_chunk_size, len(core_clauses))
    if not start < stop:
        raise ValueError("semantic chunk index is out of range")
    lines = [SEMANTIC_HEADER.rstrip(),
             f"/-! Exact semantic clauses {start} through {stop - 1} of the distinct core. -/", ""]
    for dense_index in range(start, stop):
        origin_id = origin_ids[dense_index]
        lines += semantic_clause_lemma(
            origin_id, categories[origin_id - 1], core_clauses[dense_index], reverse_names)
    lines += ["end ErdosSzekeres", "", "end", ""]
    args.output.write_text("\n".join(lines))
    print(json.dumps({
        "chunk": args.semantic_chunk_index,
        "dense_start": start,
        "dense_stop": stop,
        "categories": sorted({categories[origin_ids[i] - 1] for i in range(start, stop)}),
        "sha256": hashlib.sha256(args.output.read_bytes()).hexdigest(),
    }, sort_keys=True))


def semantic_clause_invocation(original_id: int, category: str,
                               literals: tuple[int, ...], reverse_names: dict[int, str]) -> str:
    lemma = f"pascal556WitnessReuseFin14_clause{original_id:06d}_valid χ cut"
    if category == "one_change":
        return lemma + " hone"
    if category == "no_cap_five":
        return lemma + " hnoCap"
    if category == "no_cup_five":
        return lemma + " hnoCup"
    if category == "no_strong_six":
        return lemma + " hnoStrong"
    if category == "side_no_cap_four":
        cut_literal = next(x for x in literals
                           if reverse_names[abs(x)].startswith("cut."))
        cut_value = int(reverse_names[abs(cut_literal)].split(".")[1])
        quad = clause_vertices(literals, reverse_names, "color")
        return lemma + (" hnoLeft" if all(v < cut_value for v in quad) else " hnoRight")
    return lemma


def generate_semantic_final(args: argparse.Namespace) -> None:
    if args.semantic_builder is None or args.semantic_map is None:
        raise ValueError("semantic final requires --semantic-builder and --semantic-map")
    variable_count, core_clauses = parse_dimacs(args.cnf)
    origin_ids = tuple(int(text) for text in args.semantic_origin.read_text().split())
    mapping = json.loads(args.semantic_map.read_text())
    reverse_names = {value: name for name, value in mapping["variable_map"].items()}
    formula, categories = load_frozen_formula(args.semantic_builder)
    if variable_count != mapping["variables"] or formula.names != mapping["variable_map"]:
        raise ValueError("semantic final variable map mismatch")
    if len(origin_ids) != len(core_clauses):
        raise ValueError("semantic final origin/core length mismatch")
    for origin_id, clause in zip(origin_ids, core_clauses):
        if formula.clauses[origin_id - 1] != clause:
            raise ValueError(f"semantic final clause mismatch at origin {origin_id}")
    chunk_count = (len(core_clauses) + args.semantic_chunk_size - 1) // args.semantic_chunk_size
    lines = ["-- Generated by generate_pascal556_witness_reuse_fin14_lean.py; do not edit.",
             "module", "",
             "public import ErdosSzekeres.Pascal556WitnessReuseFin14TwoReified"]
    lines += [f"public import ErdosSzekeres.Pascal556WitnessReuseFin14TwoSemanticChunk{i:03d}"
              for i in range(chunk_count)]
    lines += [
        "", "@[expose] public section", "", "namespace ErdosSzekeres", "",
        "set_option maxHeartbeats 0", "set_option maxRecDepth 20000", "",
        "/-- The independently checked distinct-witness core proves the stronger",
        "normalized base contradiction, without any witness or probe premise. -/",
        "theorem pascal556WitnessReuseFin14BaseForbidden_impossible",
        "    (χ : TripleColoring 14) (cut : Fin 8) :",
        "    ¬Pascal556WitnessReuseFin14BaseForbidden χ cut := by",
        "  rintro ⟨hone, hnoCap, hnoCup, hnoStrong, hnoLeft, hnoRight⟩",
        "  have hbad := pascal556WitnessReuseFin14TwoReified",
    ]
    atoms = [f"({semantic_atom_term(reverse_names[i])})" for i in range(1, variable_count + 1)]
    for start in range(0, len(atoms), 4):
        lines.append("    " + " ".join(atoms[start:start + 4]))
    lines.append("  simp only [")
    for origin_id, clause in zip(origin_ids, core_clauses):
        lines.append("    " + semantic_clause_invocation(
            origin_id, categories[origin_id - 1], clause, reverse_names) + ",")
    lines += ["    false_or, or_false", "  ] at hbad", "", "end ErdosSzekeres", "", "end", ""]
    args.output.write_text("\n".join(lines))
    print(json.dumps({
        "clauses": len(core_clauses), "variables": variable_count,
        "chunks": chunk_count, "sha256": hashlib.sha256(args.output.read_bytes()).hexdigest(),
    }, sort_keys=True))


def balanced_or(expressions: list[str], indent: int = 2) -> str:
    if not expressions:
        raise ValueError("cannot balance an empty disjunction")
    if len(expressions) == 1:
        return expressions[0]
    middle = len(expressions) // 2
    left = balanced_or(expressions[:middle], indent + 2)
    right = balanced_or(expressions[middle:], indent + 2)
    padding = " " * indent
    return f"({left} ∨\n{padding}{right})"


def tree_ranges(size: int, depth: int) -> list[tuple[int, int]]:
    ranges = [(0, size)]
    for _ in range(depth):
        next_ranges = []
        for start, stop in ranges:
            middle = start + (stop - start) // 2
            next_ranges.extend(((start, middle), (middle, stop)))
        ranges = next_ranges
    return ranges


