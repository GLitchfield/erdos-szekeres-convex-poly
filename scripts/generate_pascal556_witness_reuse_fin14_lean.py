def raw(value: str) -> str:
    if '\"#' in value:
        raise ValueError("input unexpectedly terminates a one-hash raw string")
    return 'r#"' + value + '"#'


def generate_checkpoint_modules(args: argparse.Namespace) -> None:
    if args.checkpoint_dir is None or args.lean_dir is None:
        raise ValueError("checkpoint generation requires --checkpoint-dir and --lean-dir")
    prefix = args.checkpoint_prefix
    if not prefix.startswith("Pascal556WitnessReuseFin14") or not prefix.isidentifier():
        raise ValueError("checkpoint prefix must be an owned Lean-compatible module prefix")
    args.checkpoint_dir.mkdir(parents=True, exist_ok=True)
    args.lean_dir.mkdir(parents=True, exist_ok=True)
    splitter = Path(__file__).with_name("split_lrat_checkpoints.py")
    with tempfile.TemporaryDirectory(prefix="pascal556-checkpoint-modules-") as temporary:
        command = [
            "python3", str(splitter), str(args.cnf), str(args.lrat),
            str(args.checkpoint_dir), "--original-clauses", str(args.original_clauses),
            "--segments", str(args.segments), "--lean-prefix", prefix,
            "--lean-dir", temporary, "--bundle-size", str(args.bundle_size), "--quiet",
        ]
        subprocess.run(command, check=True)

    metadata = json.loads((args.checkpoint_dir / "metadata.json").read_text())
    cnf = args.cnf.read_text()
    context_name = f"{prefix}Context"
    context = f'''-- Generated by {Path(__file__).name}; do not edit.
module

public import ErdosSzekeres.Pascal556WitnessReuseFin14Checkpoint

@[expose] public section

namespace ErdosSzekeres

def {prefix}Cnf : String :=
  {raw(cnf)}

lrat_checkpoint_context {context_name}
  {prefix}Cnf

end ErdosSzekeres

end
'''
    (args.lean_dir / f"{context_name}.lean").write_text(context)

    for segment in range(args.segments):
        module_name = f"{prefix}Segment{segment:03d}"
        imports = "".join(
            f"import ErdosSzekeres.{prefix}Segment{prior:03d}\n"
            for prior in metadata["direct_imports_by_segment"][segment]
        )
        lrat = (args.checkpoint_dir / f"segment-{segment:03d}.lrat").read_text()
        carry_input = (
            args.checkpoint_dir / f"carry-input-{segment:03d}.txt"
        ).read_text()
        carry_output = (
            args.checkpoint_dir / f"carry-output-{segment:03d}.txt"
        ).read_text()
        if segment + 1 == args.segments:
            command_body = f'''lrat_checkpoint_final_proof {context_name} {prefix}
  {prefix}Cnf
  {raw(lrat)}
  {raw(carry_input)}'''
        else:
            command_body = f'''lrat_checkpoint_segment {context_name} {prefix} {segment} {args.bundle_size}
  {prefix}Cnf
  {raw(lrat)}
  {raw(carry_input)}
  {raw(carry_output)}'''
        source = f'''-- Generated by {Path(__file__).name}; do not edit.
module

public import ErdosSzekeres.{context_name}
{imports}
public section

namespace ErdosSzekeres

set_option maxHeartbeats 0

{command_body}

end ErdosSzekeres

end
'''
        (args.lean_dir / f"{module_name}.lean").write_text(source)
    print(
        f"generated checkpoint modules {context_name} and {args.segments} segments; "
        f"{metadata['learned_additions']} additions"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cnf", type=Path, required=True)
    parser.add_argument("--lrat", type=Path, required=True)
    parser.add_argument("--theorem")
    parser.add_argument("--output", type=Path)
    parser.add_argument("--checkpoint-prefix")
    parser.add_argument("--checkpoint-dir", type=Path)
    parser.add_argument("--lean-dir", type=Path)
    parser.add_argument("--original-clauses", type=int)
    parser.add_argument("--segments", type=int, default=32)
    parser.add_argument("--bundle-size", type=int, default=256)
    parser.add_argument("--semantic-builder", type=Path)
    parser.add_argument("--semantic-map", type=Path)
    parser.add_argument("--semantic-origin", type=Path)
    parser.add_argument("--semantic-chunk-index", type=int)
    parser.add_argument("--semantic-chunk-size", type=int, default=64)
    parser.add_argument("--semantic-final", action="store_true")
    parser.add_argument("--semantic-eliminator-index", type=int)
    parser.add_argument("--semantic-balanced-final", action="store_true")
    args = parser.parse_args()
    if args.semantic_balanced_final:
        if args.semantic_origin is None or args.output is None:
            parser.error("balanced final requires --semantic-origin and --output")
        generate_semantic_balanced_final(args)
        return
    if args.semantic_eliminator_index is not None:
        if args.semantic_origin is None or args.output is None:
            parser.error("semantic eliminator requires --semantic-origin and --output")
        generate_semantic_eliminator(args)
        return
    if args.semantic_final:
        if args.semantic_origin is None or args.output is None:
            parser.error("semantic final requires --semantic-origin and --output")
        generate_semantic_final(args)
        return
    if args.semantic_chunk_index is not None:
        if args.semantic_origin is None or args.output is None:
            parser.error("semantic generation requires --semantic-origin and --output")
        generate_semantic_chunk(args)
        return
    if args.checkpoint_prefix is not None:
        if args.original_clauses is None:
            parser.error("--checkpoint-prefix requires --original-clauses")
        generate_checkpoint_modules(args)
        return
    if args.theorem is None or args.output is None:
        parser.error("single-module generation requires --theorem and --output")
    cnf = args.cnf.read_text()
    lrat = args.lrat.read_text()
    body = (
        HEADER
        + f"/-- Kernel-checked causal LRAT core for `{args.theorem}`. -/\n"
        + f"lrat_core_proof {args.theorem}\n  {raw(cnf)}\n  {raw(lrat)}\n"
        + FOOTER
    )
    args.output.write_text(body)
    print(f"generated {args.output}: {len(body.encode())} bytes")


if __name__ == "__main__":
    main()
