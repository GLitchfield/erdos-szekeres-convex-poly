def parse_dimacs(path: Path) -> tuple[int, tuple[tuple[int, ...], ...]]:
    variable_count = None
    expected_clauses = None
    clauses: list[tuple[int, ...]] = []
    for text in path.read_text().splitlines():
        if not text or text.startswith("c"):
            continue
        fields = text.split()
        if fields[0] == "p":
            variable_count = int(fields[2])
            expected_clauses = int(fields[3])
            continue
        values = tuple(map(int, fields))
        if not values or values[-1] != 0:
            raise ValueError(f"unterminated DIMACS clause in {path}")
        clauses.append(values[:-1])
    if variable_count is None or expected_clauses != len(clauses):
        raise ValueError(f"bad DIMACS header in {path}")
    return variable_count, tuple(clauses)


def load_frozen_formula(builder: Path):
    """Reconstruct the frozen clauses plus their generation categories."""
    generator_path = builder / "generate_cnf.py"
    spec = importlib.util.spec_from_file_location("pascal556_frozen_generator", generator_path)
    if spec is None or spec.loader is None:
        raise ValueError("cannot load frozen Fin14 generator")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    original_add = module.Cnf.add

    def recording_add(self, category, *literals):
        original_add(self, category, *literals)
        if not hasattr(self, "category_rows"):
            self.category_rows = []
        self.category_rows.append(category)

    module.Cnf.add = recording_add
    formula = module.build_formula()
    if len(formula.category_rows) != len(formula.clauses):
        raise ValueError("category reconstruction lost synchronization")
    return formula, tuple(formula.category_rows)


def semantic_atom_term(name: str) -> str:
    fields = name.split(".")
    stem = fields[0]
    if stem == "color":
        a, b, c = fields[1:]
        return ("Pascal556WitnessReuseFin14ColorAtom χ "
                f"{a} {b} {c} (by decide) (by decide)")
    if stem == "strong4":
        a, b, c, d = fields[1:]
        return ("Pascal556WitnessReuseFin14Strong4Atom χ "
                f"{a} {b} {c} {d} (by decide) (by decide) (by decide)")
    if stem == "strong5":
        a, b, c, d, e = fields[1:]
        return ("Pascal556WitnessReuseFin14Strong5Atom χ "
                f"{a} {b} {c} {d} {e} (by decide) (by decide) (by decide) (by decide)")
    if stem == "cut":
        return f"cut.val = {fields[1]}"
    if name.startswith("aux.cut_exactly_one.amo."):
        return f"cut.val ≤ {int(fields[-1]) - 1}"
    return "True"


def semantic_failure(literals: tuple[int, ...], reverse_names: dict[int, str]) -> str:
    pieces = []
    for literal in literals:
        atom = semantic_atom_term(reverse_names[abs(literal)])
        pieces.append(f"¬({atom})" if literal > 0 else f"({atom})")
    return " ∧\n      ".join(pieces)


def color_term(vertices: tuple[int, int, int]) -> str:
    a, b, c = vertices
    return f"χ ⟨{a}, {b}, {c}, by decide, by decide⟩"


def clause_vertices(literals: tuple[int, ...], reverse_names: dict[int, str], stem: str):
    result = set()
    for literal in literals:
        fields = reverse_names[abs(literal)].split(".")
        if fields[0] == stem:
            result.update(map(int, fields[1:]))
    return tuple(sorted(result))


def semantic_one_change_lemma(original_id: int, literals: tuple[int, ...],
                               reverse_names: dict[int, str]) -> list[str]:
    quad = clause_vertices(literals, reverse_names, "color")
    if len(quad) != 4:
        raise ValueError(f"one-change clause {original_id} has no unique quad")
    a, b, c, d = quad
    colors = ((a, b, c), (a, b, d), (a, c, d), (b, c, d))
    lines = [
        f"theorem pascal556WitnessReuseFin14_clause{original_id:06d}_valid",
        "    (χ : TripleColoring 14) (cut : Fin 8)",
        "    (hone : OneChangeOn χ Finset.univ) :",
        f"    ¬({semantic_failure(literals, reverse_names)}) := by",
        "  intro hbad",
        f"  have hallowed := hone (i := {a}) (j := {b}) (k := {c}) (l := {d})",
        "    (by decide) (by decide) (by decide) (by simp) (by simp) (by simp) (by simp)",
    ]
    for index, triple in enumerate(colors):
        lines.append(f"  cases hcolor{index} : {color_term(triple)} <;>")
    lines += [
        "    simp_all [Pascal556WitnessReuseFin14ColorAtom, TurnSequenceAllowed]",
        "",
    ]
    return lines


