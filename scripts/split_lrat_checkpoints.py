#!/usr/bin/env python3
"""Split an LRAT proof into kernel-checkable Lean checkpoint modules.

The generated manifests are untrusted proof inputs.  `LRATCheckpoint.lean`
turns every carried clause into an ordinary theorem and the Lean kernel checks
every generated declaration.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path


def segment_at(offset: int, size: int, count: int) -> int:
    return min(count - 1, offset * count // size)


def parse_addition(raw: bytes, offset: int) -> tuple[int, list[bytes], list[int]] | None:
    fields = raw.split()
    if not fields:
        return None
    if len(fields) >= 2 and fields[1] == b"d":
        return None
    try:
        first_zero = fields.index(b"0", 1)
        second_zero = fields.index(b"0", first_zero + 1)
    except ValueError as exc:
        raise ValueError(f"unterminated LRAT addition at byte {offset}") from exc
    clause_id = int(fields[0])
    literals = fields[1:first_zero]
    references = [abs(int(token)) for token in fields[first_zero + 1 : second_zero]]
    return clause_id, literals, references


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def include_path(path: Path, module_dir: Path) -> str:
    relative = os.path.relpath(path.resolve(), module_dir.resolve())
    return relative.replace(os.sep, "/")


def parse_bundle_size_overrides(
    specifications: list[str], segment_count: int
) -> dict[int, int]:
    result: dict[int, int] = {}
    for specification in specifications:
        try:
            segment_text, size_text = specification.split(":", 1)
            segment = int(segment_text)
            size = int(size_text)
        except ValueError as exc:
            raise ValueError(
                f"invalid bundle-size override {specification!r}; expected SEGMENT:SIZE"
            ) from exc
        if not 0 <= segment < segment_count:
            raise ValueError(f"bundle-size override segment out of range: {segment}")
        if size < 1:
            raise ValueError(f"bundle-size override must be positive: {size}")
        if segment in result:
            raise ValueError(f"duplicate bundle-size override for segment {segment}")
        result[segment] = size
    return result


def write_context_module(
    path: Path,
    prefix: str,
    cnf_include: str,
) -> None:
    path.write_text(
        f"""-- Generated by scripts/split_lrat_checkpoints.py; do not edit.
module

public import ErdosSzekeres.LRATCheckpoint

@[expose] public section

namespace ErdosSzekeres

-- The checkpoint projections are proof infrastructure, not useful premises.
run_cmd
  Lean.modifyEnv fun env =>
    Lean.LibrarySuggestions.nameDenyListExt.addEntry env "{prefix}"

lrat_checkpoint_context {prefix}Context
  (include_str \"{cnf_include}\")

end ErdosSzekeres

end
"""
    )


def write_segment_module(
    path: Path,
    prefix: str,
    segment: int,
    bundle_size: int,
    context_name: str,
    private_import_names: list[str],
    cnf_include: str,
    lrat_include: str,
    carry_input_include: str,
    carry_output_include: str,
    compact_final: bool = False,
) -> None:
    private_imports = "".join(
        f"import ErdosSzekeres.{name}\n" for name in private_import_names
    )
    final_import = (
        "public import ErdosSzekeres.LRATCheckpointFinal\n"
        if compact_final
        else ""
    )
    command = (
        "lrat_checkpoint_final_segment" if compact_final else "lrat_checkpoint_segment"
    )
    path.write_text(
        f"""-- Generated by scripts/split_lrat_checkpoints.py; do not edit.
module

public import ErdosSzekeres.{context_name}
{final_import}{private_imports}

public section

namespace ErdosSzekeres

set_option maxHeartbeats 0

{command} {prefix}Context {prefix} {segment} {bundle_size}
  (include_str \"{cnf_include}\")
  (include_str \"{lrat_include}\")
  (include_str \"{carry_input_include}\")
  (include_str \"{carry_output_include}\")

end ErdosSzekeres

end
"""
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("cnf", type=Path)
    parser.add_argument("lrat", type=Path)
    parser.add_argument("output_dir", type=Path)
    parser.add_argument("--original-clauses", type=int, required=True)
    parser.add_argument("--segments", type=int, default=4)
    parser.add_argument("--lean-prefix", required=True)
    parser.add_argument("--lean-dir", type=Path, default=Path("ErdosSzekeres"))
    parser.add_argument("--bundle-size", type=int, default=4096)
    parser.add_argument(
        "--bundle-size-override",
        action="append",
        default=[],
        metavar="SEGMENT:SIZE",
    )
    parser.add_argument("--quiet", action="store_true")
    parser.add_argument("--compact-final", action="store_true")
    args = parser.parse_args()
    if args.segments < 2:
        parser.error("--segments must be at least two")
    if not args.lean_prefix.isidentifier():
        parser.error("--lean-prefix must be a Lean-compatible identifier")
    if args.bundle_size < 1:
        parser.error("--bundle-size must be positive")
    try:
        bundle_size_overrides = parse_bundle_size_overrides(
            args.bundle_size_override, args.segments
        )
    except ValueError as exc:
        parser.error(str(exc))

    size = args.lrat.stat().st_size
    introduced: dict[int, int] = {}
    last_reference: dict[int, int] = {}
    imported_by_segment: list[set[int]] = [set() for _ in range(args.segments)]
    final_empty_id: int | None = None
    final_empty_segment: int | None = None
    additions = [0] * args.segments
    deletions = [0] * args.segments

    with args.lrat.open("rb") as source:
        while True:
            offset = source.tell()
            raw = source.readline()
            if not raw:
                break
            segment = segment_at(offset, size, args.segments)
            fields = raw.split()
            if len(fields) >= 2 and fields[1] == b"d":
                deletions[segment] += 1
                continue
            parsed = parse_addition(raw, offset)
            if parsed is None:
                continue
            additions[segment] += 1
            clause_id, literals, references = parsed
            if clause_id in introduced:
                raise ValueError(f"duplicate learned clause id {clause_id}")
            introduced[clause_id] = segment
            if not literals:
                final_empty_id = clause_id
                final_empty_segment = segment
            for reference in references:
                if reference <= args.original_clauses:
                    continue
                defining_segment = introduced.get(reference)
                if defining_segment is None:
                    raise ValueError(
                        f"clause {clause_id} references unknown learned clause {reference}"
                    )
                last_reference[reference] = segment
                if defining_segment < segment:
                    imported_by_segment[segment].add(reference)

    if final_empty_id is None or final_empty_segment != args.segments - 1:
        raise ValueError("the final segment must contain an empty learned clause")

    exported_by_segment: list[set[int]] = [set() for _ in range(args.segments)]
    for clause_id, last_segment in last_reference.items():
        defining_segment = introduced[clause_id]
        if defining_segment < last_segment:
            exported_by_segment[defining_segment].add(clause_id)

    args.output_dir.mkdir(parents=True, exist_ok=True)
    args.lean_dir.mkdir(parents=True, exist_ok=True)
    segment_paths = [args.output_dir / f"segment-{i:03d}.lrat" for i in range(args.segments)]
    outputs = [path.open("wb") for path in segment_paths]
    exported_literals: dict[int, bytes] = {}
    try:
        with args.lrat.open("rb") as source:
            while True:
                offset = source.tell()
                raw = source.readline()
                if not raw:
                    break
                segment = segment_at(offset, size, args.segments)
                outputs[segment].write(raw)
                parsed = parse_addition(raw, offset)
                if parsed is None:
                    continue
                clause_id, literals, _ = parsed
                if clause_id in exported_by_segment[segment]:
                    exported_literals[clause_id] = b" ".join(literals)
    finally:
        for output in outputs:
            output.close()

    carry_input_paths = []
    carry_output_paths = []
    ordered_exports = [sorted(values) for values in exported_by_segment]
    export_indices = [
        {clause_id: index for index, clause_id in enumerate(values)}
        for values in ordered_exports
    ]
    for segment in range(args.segments):
        carry_input_path = args.output_dir / f"carry-input-{segment:03d}.txt"
        carry_output_path = args.output_dir / f"carry-output-{segment:03d}.txt"
        with carry_input_path.open("wb") as output:
            for clause_id in sorted(imported_by_segment[segment]):
                defining_segment = introduced[clause_id]
                export_index = export_indices[defining_segment][clause_id]
                defining_bundle_size = bundle_size_overrides.get(
                    defining_segment, args.bundle_size
                )
                bundle_number = export_index // defining_bundle_size
                bundle_start = bundle_number * defining_bundle_size
                bundle_size = min(
                    defining_bundle_size,
                    len(ordered_exports[defining_segment]) - bundle_start,
                )
                bundle_index = export_index - bundle_start
                literals = exported_literals[clause_id]
                output.write(
                    (
                        f"{clause_id} {defining_segment} {bundle_number} "
                        f"{bundle_size} {bundle_index} "
                    ).encode()
                    + literals
                    + b" 0\n"
                )
        carry_output_path.write_text(
            "\n".join(str(value) for value in ordered_exports[segment])
            + ("\n" if ordered_exports[segment] else "")
        )
        carry_input_paths.append(carry_input_path)
        carry_output_paths.append(carry_output_path)

    context_name = f"{args.lean_prefix}Context"
    context_path = args.lean_dir / f"{context_name}.lean"
    cnf_include = include_path(args.cnf, args.lean_dir)
    write_context_module(context_path, args.lean_prefix, cnf_include)
    module_paths = [context_path]
    direct_imports_by_segment = []
    for segment in range(args.segments):
        module_name = f"{args.lean_prefix}Segment{segment:03d}"
        module_path = args.lean_dir / f"{module_name}.lean"
        defining_segments = sorted(
            {introduced[clause_id] for clause_id in imported_by_segment[segment]}
        )
        private_import_names = [
            f"{args.lean_prefix}Segment{defining_segment:03d}"
            for defining_segment in defining_segments
        ]
        write_segment_module(
            module_path,
            args.lean_prefix,
            segment,
            bundle_size_overrides.get(segment, args.bundle_size),
            context_name,
            private_import_names,
            cnf_include,
            include_path(segment_paths[segment], args.lean_dir),
            include_path(carry_input_paths[segment], args.lean_dir),
            include_path(carry_output_paths[segment], args.lean_dir),
            compact_final=args.compact_final and segment == args.segments - 1,
        )
        module_paths.append(module_path)
        direct_imports_by_segment.append(defining_segments)

    metadata = {
        "cnf": str(args.cnf),
        "cnf_sha256": sha256(args.cnf),
        "lrat": str(args.lrat),
        "lrat_sha256": sha256(args.lrat),
        "segments": args.segments,
        "original_clauses": args.original_clauses,
        "bundle_size": args.bundle_size,
        "bundle_size_overrides": {
            str(segment): size for segment, size in sorted(bundle_size_overrides.items())
        },
        "compact_final": args.compact_final,
        "learned_additions": len(introduced),
        "final_empty_id": final_empty_id,
        "additions_by_segment": additions,
        "deletions_by_segment": deletions,
        "imports_by_segment": [len(values) for values in imported_by_segment],
        "exports_by_segment": [len(values) for values in exported_by_segment],
        "direct_imports_by_segment": direct_imports_by_segment,
        "segment_sha256": [sha256(path) for path in segment_paths],
        "lean_modules": [str(path) for path in module_paths],
    }
    (args.output_dir / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
    if not args.quiet:
        print(json.dumps(metadata, indent=2))


if __name__ == "__main__":
    main()
