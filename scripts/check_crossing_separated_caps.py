#!/usr/bin/env python3
"""Exhaustively test the crossing separated-four-cap root proposition.

The finite model is the repository's abstract ``TripleColoring`` model, not
coordinates or certified realizable order types.  Vertices are ``range(n)``.
Increasing triples are packed in lexicographic order, least-significant bit
first, with 1 = ``Turn.left`` and 0 = ``Turn.right``.

A coloring is recursively decomposable when it is generated by a nonempty
ordered bipartition at every internal node.  On a triple crossing a node, its
bit is 1 exactly when its middle vertex belongs to the lower child.  States
are deduplicated by their complete packed triple-color vector.

For every such coloring on at most eight vertices, this checker tests every
nonempty full-set bipartition satisfying ``HasDeepBelowSplit`` for which both
child restrictions are recursively decomposable.  Thus it traverses exactly
the roots admitted by the frozen proposition, not arbitrary compatible
bipartitions of a decomposable parent.

The tested proposition says that two ordered weakly separated four-caps, each
meeting both root children, cannot coexist with the simultaneous absence of a
five-cap, a six-cup, and a strong six-set.  Predicates are recomputed directly
from packed triple bits; no state-566 table, certificate, or summary is read.

The same exact-root traversal also enumerates every nonempty weakly ordered
chain of crossing four-caps.  A chain is a sequence whose every earlier member
is weakly before every later member.  It checks lower endpoint incidence,
forced directions at shared vertices, per-lower-vertex capacity two, and the
summed two-port bound.

A mathematical counterexample is a successful checker result and therefore
does not cause a nonzero exit.  Nonzero exit is reserved for an internal
control or witness-replay failure.
"""

from __future__ import annotations

import hashlib
import functools
import itertools
