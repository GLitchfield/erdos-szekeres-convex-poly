#!/usr/bin/env python3
"""Analyze classical rank/downset states at the k=6 singleton root.

This bounded redirect experiment enumerates every recursively decomposable
coloring of the fixed upper child {0,2,...,8}.  It tests whether either the
ordered word of clipped vertex downsets or the complete clipped pair-rank
matrix determines the corresponding state after adjoining the lower singleton
{1}.  It also builds the empirical compatibility graph of parent downsets.

The experiment is purely combinatorial: decomposition trees produce rank-three
signotopes, but the script does not certify planar sweep realizability.
"""

from __future__ import annotations

import argparse
import functools
import hashlib
import itertools
import json
import os
import subprocess
from pathlib import Path
from typing import TypeAlias


Tree: TypeAlias = int | tuple["Tree", "Tree"]
N = 9
K = 6
CLIP = K - 2
LOWER = 1 << 1
FULL = (1 << N) - 1
UPPER = FULL ^ LOWER
TRIPLES = tuple(itertools.combinations(range(N), 3))
POSITIONS = {triple: position for position, triple in enumerate(TRIPLES)}
HEX_WIDTH = (len(TRIPLES) + 3) // 4


@functools.cache
def crossing_bits(mask: int, lower: int) -> int:
    answer = 0
    for position, (i, j, k) in enumerate(TRIPLES):
        selected = (1 << i) | (1 << j) | (1 << k)
        if selected & mask == selected:
            count = (selected & lower).bit_count()
            if 0 < count < 3 and lower & (1 << j):
                answer |= 1 << position
    return answer


def proper_submasks(mask: int):
    child = (mask - 1) & mask
    while child:
        yield child
        child = (child - 1) & mask


def enumerate_upper_colorings() -> dict[int, Tree]:
    states: dict[int, dict[int, Tree]] = {}
    for size in range(1, UPPER.bit_count() + 1):
        mask = UPPER
        while mask:
            if mask.bit_count() == size:
                if size == 1:
                    states[mask] = {0: (mask & -mask).bit_length() - 1}
                else:
                    answers: dict[int, Tree] = {}
                    for lower in proper_submasks(mask):
                        upper = mask ^ lower
                        fixed = crossing_bits(mask, lower)
                        for left_bits, left_tree in sorted(states[lower].items()):
                            for right_bits, right_tree in sorted(states[upper].items()):
                                bits = left_bits | right_bits | fixed
                                answers.setdefault(bits, (left_tree, right_tree))
                    states[mask] = answers
            mask = (mask - 1) & UPPER
    return states[UPPER]


def turn(bits: int, a: int, b: int, c: int) -> bool:
    return bool(bits & (1 << POSITIONS[(a, b, c)]))


def contains_strong_six(bits: int) -> bool:
    for chain in itertools.combinations(range(N), K):
        strong = True
        for a, b, c, d in itertools.combinations(chain, 4):
            if turn(bits, a, b, c) != turn(bits, a, b, d):
                strong = False
                break
            if turn(bits, a, c, d) != turn(bits, b, c, d):
                strong = False
                break
        if strong:
            return True
    return False


def rank_states(bits: int, vertices: tuple[int, ...],
                clip: int = CLIP) -> tuple[tuple[int, ...], tuple[tuple[int, int], ...]]:
    """Return the downset word and consecutive-chain rank matrix.

    A pair rank is one less than the longest monochromatic consecutive chain
    ending in that pair, clipped at k-2.  A vertex downset is the union of the
    lower-left rectangles generated by its incoming (cap,cup) ranks.
    """
    ranks: dict[tuple[int, int], tuple[int, int]] = {}
    downsets: dict[int, int] = {}
    for v_index, v in enumerate(vertices):
        downset = 0
        for u_index in range(v_index):
            u = vertices[u_index]
            cap = cup = 1
            for w in vertices[:u_index]:
                old_cap, old_cup = ranks[(w, u)]
                if turn(bits, w, u, v):
                    cup = max(cup, min(clip, old_cup + 1))
                else:
                    cap = max(cap, min(clip, old_cap + 1))
            ranks[(u, v)] = cap, cup
            for a in range(cap):
                for b in range(cup):
                    downset |= 1 << (clip * a + b)
        downsets[v] = downset
    word = tuple(downsets[v] for v in vertices)
    matrix = tuple(ranks[pair] for pair in itertools.combinations(vertices, 2))
    return word, matrix


def tree_json(tree: Tree) -> object:
    if isinstance(tree, int):
        return tree
    return {"lower": tree_json(tree[0]), "upper": tree_json(tree[1])}


def git_revision(repo: Path) -> str:
    completed = subprocess.run(
        ["git", "--git-dir=.git-data", "--work-tree=.", "rev-parse", "HEAD"],
        cwd=repo, check=True, text=True, stdout=subprocess.PIPE,
    )
    return completed.stdout.strip()


def file_sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def digest_lines(lines) -> str:
    digest = hashlib.sha256()
    for line in lines:
        digest.update(line.encode())
        digest.update(b"\n")
    return digest.hexdigest()


def maximum_clique(vertices: list[int], edges: set[tuple[int, int]]) -> tuple[int, ...]:
    neighbors = {
        vertex: {other for other in vertices if other != vertex and
                 (min(vertex, other), max(vertex, other)) in edges}
        for vertex in vertices
    }
    best: tuple[int, ...] = ()

    def search(chosen: tuple[int, ...], candidates: set[int]) -> None:
        nonlocal best
        if len(chosen) + len(candidates) <= len(best):
            return
        if not candidates:
            if len(chosen) > len(best):
                best = tuple(sorted(chosen))
            return
        pivot = max(candidates, key=lambda x: len(candidates & neighbors[x]))
        for vertex in sorted(candidates - neighbors[pivot]):
            search(chosen + (vertex,), candidates & neighbors[vertex])
            candidates.remove(vertex)
            if len(chosen) + len(candidates) <= len(best):
                return

    search((), set(vertices))
    return best


def first_difference(left: tuple, right: tuple) -> dict[str, object]:
    for index, (a, b) in enumerate(zip(left, right)):
        if a != b:
            return {"index": index, "left": a, "right": b}
    raise AssertionError("states were equal")


def analyze() -> dict[str, object]:
    upper_colorings = enumerate_upper_colorings()
    upper_vertices = tuple(vertex for vertex in range(N) if UPPER & (1 << vertex))
    fixed = crossing_bits(FULL, LOWER)
    downset_seen: dict[tuple[int, ...], tuple[tuple[int, ...], int, int, Tree]] = {}
    matrix_seen: dict[tuple[tuple[int, int], ...], tuple[tuple[tuple[int, int], ...], int, int, Tree]] = {}
    first_downset = None
    first_matrix = None
    downset_collisions = matrix_collisions = injectivity_violations = 0
    open_count = 0
    universe: set[int] = set()
    edges: set[tuple[int, int]] = set()
    open_rows: list[str] = []

    for upper_bits, upper_tree in sorted(upper_colorings.items()):
        parent_bits = upper_bits | fixed
        if contains_strong_six(parent_bits):
            continue
        open_count += 1
        child_word, child_matrix = rank_states(upper_bits, upper_vertices)
        parent_word, parent_matrix = rank_states(parent_bits, tuple(range(N)))
        open_rows.append(
            f"{upper_bits:0{HEX_WIDTH}x}:"
            f"{','.join(map(str, child_word))}:"
            f"{','.join(map(str, parent_word))}"
        )

        if len(set(parent_word)) != len(parent_word):
            injectivity_violations += 1
        values = sorted(set(parent_word))
        universe.update(values)
        edges.update(itertools.combinations(values, 2))

        previous_downset = downset_seen.get(child_word)
        record_downset = parent_word, upper_bits, parent_bits, upper_tree
        if previous_downset is None:
            downset_seen[child_word] = record_downset
        elif previous_downset[0] != parent_word:
            downset_collisions += 1
            if first_downset is None:
                first_downset = previous_downset, record_downset, child_word

        previous_matrix = matrix_seen.get(child_matrix)
        record_matrix = parent_matrix, upper_bits, parent_bits, upper_tree
        if previous_matrix is None:
            matrix_seen[child_matrix] = record_matrix
        elif previous_matrix[0] != parent_matrix:
            matrix_collisions += 1
            if first_matrix is None:
                first_matrix = previous_matrix, record_matrix, child_matrix

    if first_downset is None or first_matrix is None:
        raise RuntimeError("expected rank-state collisions were not found")

    clique = maximum_clique(sorted(universe), edges)
    repo = Path(__file__).resolve().parent.parent

    def collision_json(first, state_name: str) -> dict[str, object]:
        left, right, equal_child = first

        def witness(record) -> dict[str, object]:
            parent_state, upper_bits, parent_bits, upper_tree = record
            return {
                "upper_coloring_hex": f"{upper_bits:0{HEX_WIDTH}x}",
                "parent_coloring_hex": f"{parent_bits:0{HEX_WIDTH}x}",
                "upper_tree": tree_json(upper_tree),
                "parent_state": parent_state,
            }

        return {
            "state": state_name,
            "equal_child_state": equal_child,
            "first_difference": first_difference(left[0], right[0]),
            "left": witness(left),
            "right": witness(right),
        }

    coloring_digest = digest_lines(
        f"{bits:0{HEX_WIDTH}x}" for bits in sorted(upper_colorings)
    )
    edge_digest = digest_lines(f"{a},{b}" for a, b in sorted(edges))
    producer_path = Path(__file__).resolve()
    return {
        "schema_version": 1,
        "producer": "scripts/analyze_decomposable_rank_profiles.py",
        # Generation necessarily precedes the commit containing the emitted
        # certificate.  Name this as a base revision rather than implying that
        # the generated file was already present at that commit.
        "generation_base_revision": git_revision(repo),
        "producer_sha256": file_sha256(producer_path),
        "scope": {
            "n": N, "k": K, "rank_clip": CLIP,
            "lower_mask_hex": f"{LOWER:x}", "upper_mask_hex": f"{UPPER:x}",
            "crossing_bits_hex": f"{fixed:0{HEX_WIDTH}x}",
            "model": "recursively decomposable triple colorings; realizability not certified",
        },
        "search_summary": {
            "upper_coloring_count": len(upper_colorings),
            "upper_colorings_sha256": coloring_digest,
            "open_parent_count": open_count,
            "open_rank_rows_sha256": digest_lines(open_rows),
            "distinct_child_downset_words": len(downset_seen),
            "downset_word_collision_observations": downset_collisions,
            "distinct_child_pair_rank_matrices": len(matrix_seen),
            "pair_rank_matrix_collision_observations": matrix_collisions,
            "parent_vertex_downset_injectivity_violations": injectivity_violations,
        },
        "downset_collision": collision_json(first_downset, "ordered vertex-downset word"),
        "pair_rank_collision": collision_json(first_matrix, "complete ordered pair-rank matrix"),
        "parent_downset_compatibility": {
            "vertex_count": len(universe),
            "vertices": sorted(universe),
            "edge_count": len(edges),
            "edges_sha256": edge_digest,
            "maximum_clique_size": len(clique),
            "maximum_clique": clique,
        },
    }


def write_atomic(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n")
    os.replace(temporary, path)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    write_atomic(args.output, analyze())
    print(args.output)


if __name__ == "__main__":
    main()
