#!/usr/bin/env python3
"""Generate the semantic Lean bridge for the sixteen-point (5,6,6) core.

The input core must consist only of clauses from the canonical CNF generated by
``generate_signotope_state_sat.py``.  Literal order may differ.  Generated Lean
modules prove every retained clause directly from the signotope, no-cap,
no-cup, and no-strong hypotheses.
"""

from __future__ import annotations

import argparse
import itertools
from collections import defaultdict
from pathlib import Path
from typing import Callable

from generate_e3_state466_lean import (
    balanced_chunks,
    balanced_join,
    balanced_not_or_proof,
    chain_encoding,
    mismatch_theorem,
)
from generate_signotope_state_sat import generate, triples


N = 16
CAP = 5
CUP = 6
STRONG = 6
PREFIX = "E3State566"
THEOREM_PREFIX = "e3State566"
CHUNK_COUNT = 256
REFINE_AFTER = 85
REFINEMENT = 4
# Five lanes preserve the compiled prefix; the fourfold-refined tail uses six
# lanes while staying below the 16 GiB project memory ceiling.  A refined
# module-system chunk peaks near 2.5 GiB on the pinned toolchain.  The final bridge
# privately imports the compact public face of the final LRAT checkpoint, so
# downstream modules do not reload the checkpoint proof graph.
DEPENDENCY_CHAINS = 5
TAIL_DEPENDENCY_CHAINS = 6
RAW_REFINEMENT = 16
RAW_DEPENDENCY_CHAINS = 8
MID_GROUP_SIZE = 4
MID_DEPENDENCY_CHAINS = 8

CAP_VALUES = "E3State566CapFiveValues"
CUP_VALUES = "E3State566CupSixValues"
STRONG_VALUES = "E3State566StrongSixValues"
CAP_IFF = "e3State566_isCap_finFive_iff"
CUP_IFF = "e3State566_isCup_finSix_iff"
STRONG_IFF = "e3State566_isStrongPolygonOn_finSix_iff"


def write_if_changed(path: Path, contents: str) -> None:
    """Preserve Lake's compiled cache when deterministic output is unchanged."""
    if path.exists() and path.read_text(encoding="utf-8") == contents:
        return
    path.write_text(contents, encoding="utf-8")


def refined_chunks(
    items: list[str], base_count: int, refine_after: int, refinement: int
) -> list[list[str]]:
    """Preserve an initial balanced partition and refine its expensive tail."""
    base = balanced_chunks(items, base_count)
    if refine_after < 0 or refine_after > len(base):
        raise ValueError("refine-after must select a boundary in the base partition")
    if refinement == 1:
        return base
    if refinement <= 0 or refinement % 2 != 0:
        raise ValueError("refinement must be one or an even positive subtree count")
    return base[:refine_after] + [
        subchunk
        for chunk in base[refine_after:]
        for subchunk in balanced_chunks(chunk, refinement)
    ]


def restored_refinement_terms(
    item_count: int, base_count: int, refine_after: int, refinement: int,
    term: Callable[[int], str],
    combine: Callable[[list[str]], str],
) -> list[str]:
    """Reinsert refined leaves at their positions in the base expression tree.

    ``refined_chunks`` flattens the refined tail for file generation.  A flat
    rebalance of those names changes the proposition's syntax tree.  This
    helper rebuilds each refined base subtree before the base tree itself is
    rebuilt, preserving definitional equality with the original balanced CNF.
    """
    if refine_after < 0 or refine_after > base_count:
        raise ValueError("refine-after must select a boundary in the base partition")
    if refinement <= 0:
        raise ValueError("refinement must be positive")
    result: list[str] = []
    cursor = 0
    for base_index in range(base_count):
        width = 1 if base_index < refine_after else refinement
        names = [term(index) for index in range(cursor, cursor + width)]
        result.append(names[0] if width == 1 else combine(names))
        cursor += width
    expected = refine_after + (base_count - refine_after) * refinement
    if cursor != expected or item_count != expected:
        raise ValueError("refined item count does not match the base-tree layout")
    return result


def balanced_tree(items: list[object]) -> object:
    """Return the binary tree used by ``balanced_join`` without rendering it."""
    if not items:
        raise ValueError("cannot build an empty balanced tree")
    if len(items) == 1:
        return items[0]
    midpoint = len(items) // 2
    return (balanced_tree(items[:midpoint]), balanced_tree(items[midpoint:]))


def checkpoint_refutation_term(tree: object) -> str:
    """Eliminate a raw checkpoint disjunction, comparing only at chunk leaves."""
    if isinstance(tree, int):
        return f"h{tree} hbad"
    left, right = tree
    return (
        "(Or.elim hbad "
        f"(fun hbad ↦ {checkpoint_refutation_term(left)}) "
        f"(fun hbad ↦ {checkpoint_refutation_term(right)}))"
    )


def balanced_or_injection(index: int, count: int, term: str = "hbad") -> str:
    """Inject one leaf into the proposition tree rendered by ``balanced_join``."""
    if count <= 0 or index < 0 or index >= count:
        raise ValueError("balanced injection index is out of range")
    if count == 1:
        return term
    midpoint = count // 2
    if index < midpoint:
        return f"Or.inl ({balanced_or_injection(index, midpoint, term)})"
    return f"Or.inr ({balanced_or_injection(index - midpoint, count - midpoint, term)})"


def chunk_imports(index: int) -> str:
    """Imports that bound bridge parallelism while preserving the checked prefix."""
    imports = [f"module\n\npublic import ErdosSzekeres.{PREFIX}Encoding"]
    if DEPENDENCY_CHAINS <= index < REFINE_AFTER:
        imports.append(
            f"import ErdosSzekeres.{PREFIX}CNFChunk"
            f"{index - DEPENDENCY_CHAINS:03}"
        )
    elif REFINE_AFTER <= index < REFINE_AFTER + TAIL_DEPENDENCY_CHAINS:
        anchors = [
            REFINE_AFTER - DEPENDENCY_CHAINS + offset
            for offset in range(DEPENDENCY_CHAINS)
        ] + [REFINE_AFTER - DEPENDENCY_CHAINS - 1]
        imports.append(
            f"import ErdosSzekeres.{PREFIX}CNFChunk"
            f"{anchors[index - REFINE_AFTER]:03}"
        )
    elif index >= REFINE_AFTER + TAIL_DEPENDENCY_CHAINS:
        imports.append(
            f"import ErdosSzekeres.{PREFIX}CNFChunk"
            f"{index - TAIL_DEPENDENCY_CHAINS:03}"
        )
    return "\n".join(imports)


def turn_term(bit: bool) -> str:
    return "Turn.left" if bit else "Turn.right"


def tuple_arguments(prefix: str, count: int) -> str:
    return " ".join(f"{prefix}{i}" for i in range(count))


def selected_triple_term(size: int, triple: tuple[int, int, int]) -> str:
    i, j, k = triple
    return (
        f"(χ ⟨f {i}, f {j}, f {k}, f.strictMono (by decide), "
        "f.strictMono (by decide)⟩)"
    )


def values_definition(name: str, count: int, equations: list[str]) -> str:
    binders = " ".join(f"x{i}" for i in range(count))
    return f"def {name} ({binders} : Turn) : Prop :=\n  " + " ∧\n  ".join(equations)


def strong_encoding() -> str:
    local_triples = triples(range(STRONG))
    position = {triple: i for i, triple in enumerate(local_triples)}
    equations: list[str] = []
    for i, j, k, l in itertools.combinations(range(STRONG), 4):
        equations.append(f"x{position[i, j, k]} = x{position[i, j, l]}")
        equations.append(f"x{position[i, k, l]} = x{position[j, k, l]}")
    values = values_definition(STRONG_VALUES, len(local_triples), equations)
    actual = "\n        ".join(selected_triple_term(STRONG, t) for t in local_triples)
    forward_items: list[str] = []
    for i, j, k, l in itertools.combinations(range(STRONG), 4):
        call = (
            f"h (i := {i}) (j := {j}) (k := {k}) (l := {l}) "
            "(by decide) (by decide) (by decide)"
        )
        forward_items.extend([
            f"(by simpa [TripleColoring.restrict, OrderedTriple.map] using ({call}).1)",
            f"(by simpa [TripleColoring.restrict, OrderedTriple.map] using ({call}).2)",
        ])
    forward = ",\n      ".join(forward_items)
    hypotheses = ", ".join(f"h{i}" for i in range(len(equations)))
    cases = " <;> ".join(f"fin_cases {v}" for v in "ijkl")
    theorem = f'''theorem {STRONG_IFF} {{n : ℕ}} (χ : TripleColoring n)
    (f : Fin 6 ↪o Fin n) :
    IsStrongPolygonOn χ f ↔
      {STRONG_VALUES}
        {actual} := by
  constructor
  · intro h
    exact ⟨{forward}⟩
  · rintro ⟨{hypotheses}⟩
    intro i j k l hij hjk hkl
    {cases} <;>
      simp [TripleColoring.restrict, OrderedTriple.map] at hij hjk hkl ⊢ <;> simp_all
'''
    return values + "\n\n" + theorem


def parse_core(path: Path) -> list[list[int]]:
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or not lines[0].startswith("p cnf "):
        raise ValueError("core is missing a DIMACS header")
    result = []
    for line in lines[1:]:
        if not line or line.startswith("c"):
            continue
        literals = [int(value) for value in line.split()]
        if not literals or literals[-1] != 0:
            raise ValueError(f"unterminated DIMACS clause: {line[:80]}")
        result.append(literals[:-1])
    expected = int(lines[0].split()[3])
    if len(result) != expected:
        raise ValueError(f"header declares {expected} clauses, parsed {len(result)}")
    return result


def select_core(
    clauses: list[list[int]],
    origins: list[tuple[str, tuple[int, ...], tuple[bool, ...]]],
    core: list[list[int]],
) -> tuple[list[list[int]], list[tuple[str, tuple[int, ...], tuple[bool, ...]]]]:
    available: dict[tuple[int, ...], list[int]] = defaultdict(list)
    for index, clause in enumerate(clauses):
        available[tuple(sorted(clause))].append(index)
    selected_origins = []
    for clause in core:
        key = tuple(sorted(clause))
        if not available[key]:
            raise ValueError(f"core clause is not in canonical CNF: {clause}")
        selected_origins.append(origins[available[key].pop()])
    return core, selected_origins


def write_encoding(directory: Path) -> None:
    source = '''-- Generated by scripts/generate_e3_state566_lean.py; do not edit.
module

public import ErdosSzekeres.ES5Encoding

@[expose] public section

set_option maxHeartbeats 0
set_option maxRecDepth 10000

namespace ErdosSzekeres

noncomputable section

'''
    source += chain_encoding(CAP, "right", CAP_VALUES, CAP_IFF)
    source += "\n" + chain_encoding(CUP, "left", CUP_VALUES, CUP_IFF)
    source += "\n" + strong_encoding()
    source += "\n" + mismatch_theorem(
        "e3State566_capFive_mismatch", CAP, CAP_VALUES, "IsCap", CAP_IFF
    )
    source += "\n" + mismatch_theorem(
        "e3State566_cupSix_mismatch", CUP, CUP_VALUES, "IsCup", CUP_IFF
    )
    source += "\n" + mismatch_theorem(
        "e3State566_strongSix_mismatch", STRONG, STRONG_VALUES,
        "IsStrongPolygonOn", STRONG_IFF
    )
    source += "\nend\n\nend ErdosSzekeres\n\nend\n"
    (directory / f"{PREFIX}Encoding.lean").write_text(source, encoding="utf-8")


def semantic_clause_proof(
    kind: str, vertices: tuple[int, ...], bits: tuple[bool, ...]
) -> str:
    targets = [turn_term(bit) for bit in bits]
    if kind == "quad":
        a, b, c, d = vertices
        named = " ".join(
            f"({name} := {target})" for name, target in zip("ABCD", targets)
        )
        return f'''(by
      have hm := turnSequence_mismatch
        (hallowed {a} {b} {c} {d} (by decide) (by decide) (by decide))
        {named} (by simp [TurnSequenceAllowed])
      simpa only [Turn.ne_right_iff_eq_left] using hm)'''

    size = CAP if kind == "cap" else 6
    vector = ", ".join(map(str, vertices))
    named = " ".join(f"(x{i} := {target})" for i, target in enumerate(targets))
    if kind == "cap":
        call = "e3State566_capFive_mismatch χ f (hnoCap f)"
        target = CAP_VALUES
    elif kind == "cup":
        call = "e3State566_cupSix_mismatch χ f (hnoCup f)"
        target = CUP_VALUES
    else:
        call = "e3State566_strongSix_mismatch χ f (hnoStrong f)"
        target = STRONG_VALUES
    return f'''(by
      let f : Fin {size} ↪o Fin {N} := OrderEmbedding.ofStrictMono ![{vector}] (by decide)
      have hm := {call} {named} (by simp [{target}])
      simpa only [f, Turn.ne_right_iff_eq_left] using hm)'''


def bad_clause_contradiction(proof: str, clause: list[int]) -> str:
    bad_names = ", ".join(f"hb{i}" for i in range(len(clause)))
    cases = " | ".join("hs" for _ in clause)
    contradictions = "\n".join(
        f"      · exact {'hb' + str(i) + ' hs' if lit > 0 else 'hs hb' + str(i)}"
        for i, lit in enumerate(clause)
    )
    return (
        f"(by\n      intro hbad\n      have hsat := {proof}\n"
        f"      rcases hbad with ⟨{bad_names}⟩\n"
        f"      rcases hsat with {cases}\n{contradictions})"
    )


def write_modules(
    directory: Path,
    core_path: Path,
    chunk_count: int,
    refine_after: int,
    refinement: int,
) -> tuple[int, int]:
    all_triples, clauses, origins, _, _ = generate(N, CAP, CUP, STRONG)
    clauses, origins = select_core(clauses, origins, parse_core(core_path))

    def triple_term(index: int) -> str:
        a, b, c = all_triples[index]
        return f"(χ ⟨{a}, {b}, {c}, by decide, by decide⟩ = Turn.left)"

    bad_clause_props = []
    for clause in clauses:
        bad_literals = [
            f"¬{triple_term(abs(lit) - 1)}" if lit > 0 else triple_term(abs(lit) - 1)
            for lit in clause
        ]
        bad_clause_props.append("(" + " ∧ ".join(bad_literals) + ")")
    base_prop_chunks = balanced_chunks(bad_clause_props, chunk_count)
    prop_chunks = refined_chunks(
        bad_clause_props, chunk_count, refine_after, refinement
    )
    chunk_definitions = [
        f"def {PREFIX}BadChunk{i} (χ : TripleColoring {N}) : Prop :=\n    "
        + balanced_join(chunk, "∨")
        for i, chunk in enumerate(prop_chunks)
    ]
    header = '''@[expose] public section

/- This file is generated by scripts/generate_e3_state566_lean.py. -/

set_option maxRecDepth 10000
set_option maxHeartbeats 0
set_option linter.unusedVariables false

namespace ErdosSzekeres

'''
    proofs = [
        bad_clause_contradiction(semantic_clause_proof(*origin), clause)
        for origin, clause in zip(origins, clauses)
    ]
    proof_chunks = refined_chunks(proofs, chunk_count, refine_after, refinement)
    assumptions = f'''(hallowed : ∀ (a b c d : Fin {N}),
      ∀ (hab : a < b) (hbc : b < c) (hcd : c < d),
      TurnSequenceAllowed
        (χ ⟨a, b, c, hab, hbc⟩)
        (χ ⟨a, b, d, hab, hbc.trans hcd⟩)
        (χ ⟨a, c, d, hab.trans hbc, hcd⟩)
        (χ ⟨b, c, d, hbc, hcd⟩))
    (hnoCap : ∀ f : Fin {CAP} ↪o Fin {N}, ¬ IsCap χ f)
    (hnoCup : ∀ f : Fin {CUP} ↪o Fin {N}, ¬ IsCup χ f)
    (hnoStrong : ∀ f : Fin {STRONG} ↪o Fin {N}, ¬ IsStrongPolygonOn χ f)'''
    for i, (definition, chunk) in enumerate(zip(chunk_definitions, proof_chunks)):
        theorem = (
            f"theorem {THEOREM_PREFIX}CNFChunk{i}_of_constraints "
            f"(χ : TripleColoring {N})\n"
            f"    {assumptions} : ¬ {PREFIX}BadChunk{i} χ := by\n"
            f"  unfold {PREFIX}BadChunk{i}\n"
            f"  exact {balanced_not_or_proof(chunk)}"
        )
        imports = chunk_imports(i)
        source = (
            imports + "\n\n" + header + definition + "\n\n"
            + theorem + "\n\nend ErdosSzekeres\n\nend\n"
        )
        write_if_changed(directory / f"{PREFIX}CNFChunk{i:03}.lean", source)

    raw_prop_chunks = [
        raw_chunk
        for base_chunk in base_prop_chunks
        for raw_chunk in balanced_chunks(base_chunk, RAW_REFINEMENT)
    ]
    for stale in directory.glob(f"{PREFIX}CNFBase*.lean"):
        stale.unlink()
    for raw_index, raw_props in enumerate(raw_prop_chunks):
        base_index, within_base = divmod(raw_index, RAW_REFINEMENT)
        owner_count = 1 if base_index < refine_after else refinement
        if RAW_REFINEMENT % owner_count != 0:
            raise ValueError("raw refinement must be divisible by semantic refinement")
        raw_per_owner = RAW_REFINEMENT // owner_count
        owner_offset, within_owner = divmod(within_base, raw_per_owner)
        owner = (
            base_index if base_index < refine_after
            else refine_after + (base_index - refine_after) * refinement + owner_offset
        )
        injected = balanced_or_injection(within_owner, raw_per_owner)
        raw_imports = [
            f"module\n\npublic import ErdosSzekeres.{PREFIX}Encoding",
            f"import ErdosSzekeres.{PREFIX}CNFChunk{owner:03}",
        ]
        if raw_index >= RAW_DEPENDENCY_CHAINS:
            raw_imports.append(
                f"import ErdosSzekeres.{PREFIX}CNFRaw"
                f"{raw_index - RAW_DEPENDENCY_CHAINS:04}"
            )
        theorem = f'''theorem {THEOREM_PREFIX}CNFRaw{raw_index}_of_constraints
    (χ : TripleColoring {N})
    {assumptions} : ¬ ({balanced_join(raw_props, "∨")}) := by
  have howner := {THEOREM_PREFIX}CNFChunk{owner}_of_constraints χ
    hallowed hnoCap hnoCup hnoStrong
  intro hbad
  exact howner ({injected})
'''
        source = (
            "\n".join(raw_imports) + "\n\n" + header + theorem
            + "\nend ErdosSzekeres\n\nend\n"
        )
        write_if_changed(directory / f"{PREFIX}CNFRaw{raw_index:04}.lean", source)
    expected_raw_names = {
        f"{PREFIX}CNFRaw{index:04}.lean" for index in range(len(raw_prop_chunks))
    }
    for stale in directory.glob(f"{PREFIX}CNFRaw*.lean"):
        if stale.name not in expected_raw_names:
            stale.unlink()

    for stale in directory.glob(f"{PREFIX}CNFTop*.lean"):
        stale.unlink()
    mid_prop_chunks = [
        mid_chunk
        for base_chunk in base_prop_chunks
        for mid_chunk in balanced_chunks(base_chunk, RAW_REFINEMENT // MID_GROUP_SIZE)
    ]
    for mid_index, raw_props in enumerate(mid_prop_chunks):
        raw_indices = list(range(
            mid_index * MID_GROUP_SIZE, (mid_index + 1) * MID_GROUP_SIZE
        ))
        mid_imports = [f"module\n\npublic import ErdosSzekeres.{PREFIX}Encoding"]
        mid_imports.extend(
            f"import ErdosSzekeres.{PREFIX}CNFRaw{index:04}" for index in raw_indices
        )
        if mid_index >= MID_DEPENDENCY_CHAINS:
            mid_imports.append(
                f"import ErdosSzekeres.{PREFIX}CNFMid"
                f"{mid_index - MID_DEPENDENCY_CHAINS:04}"
            )
        local_hypotheses = "\n  ".join(
            f"have h{index} := {THEOREM_PREFIX}CNFRaw{index}_of_constraints χ "
            "hallowed hnoCap hnoCup hnoStrong"
            for index in raw_indices
        )
        local_refutation = checkpoint_refutation_term(balanced_tree(raw_indices))
        theorem = f'''theorem {THEOREM_PREFIX}CNFMid{mid_index}_of_constraints
    (χ : TripleColoring {N})
    {assumptions} : ¬ ({balanced_join(raw_props, "∨")}) := by
  {local_hypotheses}
  intro hbad
  exact {local_refutation}
'''
        source = (
            "\n".join(mid_imports) + "\n\n" + header + theorem
            + "\nend ErdosSzekeres\n\nend\n"
        )
        write_if_changed(directory / f"{PREFIX}CNFMid{mid_index:04}.lean", source)
    expected_mid_names = {
        f"{PREFIX}CNFMid{index:04}.lean" for index in range(len(mid_prop_chunks))
    }
    for stale in directory.glob(f"{PREFIX}CNFMid[0-9]*.lean"):
        if stale.name not in expected_mid_names:
            stale.unlink()

    arguments = " ".join(f"({triple_term(i)})" for i in range(len(all_triples)))
    mid_public_imports = "\n".join(
        f"public import ErdosSzekeres.{PREFIX}CNFMid{i:04}"
        for i in range(len(mid_prop_chunks))
    )
    named_aliases = "\n".join(
        f"negated_conclusion_alias {PREFIX}BadMid{i} "
        f"{THEOREM_PREFIX}CNFNamedMid{i}_of_constraints from "
        f"{THEOREM_PREFIX}CNFMid{i}_of_constraints"
        for i in range(len(mid_prop_chunks))
    )
    named_mid_terms = [f"{PREFIX}BadMid{i} χ" for i in range(len(mid_prop_chunks))]
    named_checkpoint_refutation = checkpoint_refutation_term(
        balanced_tree(list(range(len(mid_prop_chunks))))
    )
    named_hypotheses = "\n  ".join(
        f"have h{i} := {THEOREM_PREFIX}CNFNamedMid{i}_of_constraints χ "
        "hallowed hnoCap hnoCup hnoStrong"
        for i in range(len(mid_prop_chunks))
    )
    definitions = f'''module

public import ErdosSzekeres.{PREFIX}Encoding
public import ErdosSzekeres.{PREFIX}CheckpointSegment255

{header}def {PREFIX}Bad (χ : TripleColoring {N}) : Prop :=
  {PREFIX}Checkpoint.bad {arguments}

def {PREFIX}CNF (χ : TripleColoring {N}) : Prop := ¬ {PREFIX}Bad χ

end ErdosSzekeres

end
'''
    unsat = f'''module

public import ErdosSzekeres.{PREFIX}CNFDefs

{header}theorem {THEOREM_PREFIX}CNF_unsat (χ : TripleColoring {N}) : ¬ {PREFIX}CNF χ := by
  intro hcnf
  exact hcnf ({PREFIX}Checkpoint.publicUnsat {arguments})

end ErdosSzekeres

end
'''
    named = f'''module

public import ErdosSzekeres.NegatedConclusionAlias
{mid_public_imports}

{header}{named_aliases}

end ErdosSzekeres

end
'''
    named_root = f'''module

public import ErdosSzekeres.{PREFIX}CNFMidNamed

{header}def {PREFIX}BadMidTree (χ : TripleColoring {N}) : Prop :=
  {balanced_join(named_mid_terms, "∨")}

theorem {THEOREM_PREFIX}CNFBadMidTree_of_constraints (χ : TripleColoring {N})
    {assumptions} : ¬ {PREFIX}BadMidTree χ := by
  {named_hypotheses}
  intro hbad
  exact {named_checkpoint_refutation}

end ErdosSzekeres

end
'''
    named_bridge = f'''module

public import ErdosSzekeres.{PREFIX}CNFNamedRoot
public import ErdosSzekeres.{PREFIX}CNFDefs

{header}theorem {THEOREM_PREFIX}Bad_eq_badMidTree (χ : TripleColoring {N}) :
    {PREFIX}Bad χ = {PREFIX}BadMidTree χ := by
  rfl

end ErdosSzekeres

end
'''
    semantics = f'''module

public import ErdosSzekeres.{PREFIX}CNFNamedBridge

{header}theorem {THEOREM_PREFIX}CNF_of_constraints (χ : TripleColoring {N})
    {assumptions} : {PREFIX}CNF χ := by
  have htree := {THEOREM_PREFIX}CNFBadMidTree_of_constraints χ
    hallowed hnoCap hnoCup hnoStrong
  unfold {PREFIX}CNF
  intro hbad
  exact htree (({THEOREM_PREFIX}Bad_eq_badMidTree χ).mp hbad)

end ErdosSzekeres

end
'''
    facade = f'''module

public import ErdosSzekeres.{PREFIX}CNFUnsat
public import ErdosSzekeres.{PREFIX}CNFSemantics
'''
    write_if_changed(directory / f"{PREFIX}CNFDefs.lean", definitions)
    write_if_changed(directory / f"{PREFIX}CNFUnsat.lean", unsat)
    write_if_changed(directory / f"{PREFIX}CNFMidNamed.lean", named)
    write_if_changed(directory / f"{PREFIX}CNFNamedRoot.lean", named_root)
    write_if_changed(directory / f"{PREFIX}CNFNamedBridge.lean", named_bridge)
    write_if_changed(directory / f"{PREFIX}CNFSemantics.lean", semantics)
    write_if_changed(directory / f"{PREFIX}CNFGenerated.lean", facade)
    return len(clauses), len(proof_chunks)
def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("directory", type=Path)
    parser.add_argument("--core-cnf", type=Path)
    parser.add_argument("--chunks", type=int, default=CHUNK_COUNT)
    parser.add_argument("--refine-after", type=int, default=REFINE_AFTER)
    parser.add_argument("--refinement", type=int, default=REFINEMENT)
    parser.add_argument("--encoding-only", action="store_true")
    args = parser.parse_args()
    args.directory.mkdir(parents=True, exist_ok=True)
    write_encoding(args.directory)
    if args.encoding_only:
        print(f"encoding={args.directory / f'{PREFIX}Encoding.lean'}")
        return
    if args.core_cnf is None:
        parser.error("--core-cnf is required unless --encoding-only is used")
    clauses, chunks = write_modules(
        args.directory,
        args.core_cnf,
        args.chunks,
        args.refine_after,
        args.refinement,
    )
    print(f"clauses={clauses} chunks={chunks} directory={args.directory}")


if __name__ == "__main__":
    main()
