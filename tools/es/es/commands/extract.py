STATE_DIRS = ("ESBlueprint", "ErdosSzekeres")  # overridden by config [extract] state_dirs


def state_dirs(cfg, existing_only: bool = True) -> list[str]:
    val = cfg.get("extract", "state_dirs")
    if val:
        return [str(x) for x in val]
    dirs = [cfg.blueprint_namespace, str(cfg.blueprint_root.relative_to(cfg.root))]
    # harness inputs the *extractor* reads (the lock, allowlist, falsifier results and config
    # only feed the status computation, which runs on every call from the cached raw output)
    for p in (cfg.destinations_file,):
        try:
            dirs.append(str(p.relative_to(cfg.root)))
        except ValueError:
            pass
    for layer in cfg.layers():
        for p in layer.prefixes:
            dirs.append(p.replace(".", "/"))
            dirs.append(p.replace(".", "/") + ".lean")
    return sorted({d for d in dirs if not existing_only or (cfg.root / d).exists()})


# Lines of nodes.json / status.md that change on every extraction or commit without
# any change of state: the timestamp, the commit and tree hashes (the tree hash covers
# the commit that contains nodes.json itself), the taint-cache counters, the environment
# module count (an incremental update can only estimate it) and how the index was produced.
VOLATILE_PREFIXES = ("Generated by", '"generated_at"', '"git_sha"', '"tree_hash"',
                     '"cached_modules"', '"scanned_constants"', '"scanned_modules"',
                     '"modules"', '"extract_mode"')


def dests_from_json(data: dict):
    """Destinations from an index, with the fields `compute` derives reset, as a fresh
    extraction would produce them."""
    dests = _dests_from_json(data)
    for d in dests:
        d.uncovered_axioms = []
        d.merged_from = None
    return dests


class NeedsFullExtract(UsageError):
    """The index cannot be updated incrementally; only a full `es extract` is trusted."""


def declared_blueprint_axioms(cfg, raw: dict) -> dict[str, list[str]]:
    """Axiom constants declared in blueprint modules (e.g. `native_decide` auxiliary axioms),
    by module. The global `nonstandard_axioms` list is every non-standard axiom seen in the
    environment, so these are the only entries a blueprint edit can add or remove."""
    ns = cfg.blueprint_namespace
    out: dict[str, set[str]] = {}
    for rec in raw.get("declarations", []):
        module = str(rec.get("module", ""))
        if rec.get("kind") == "axiom" and (module == ns or module.startswith(ns + ".")):
            out.setdefault(rec["module"], set()).add(rec["name"])
    return {m: sorted(v) for m, v in sorted(out.items())}


NODE_RECORD_KEYS = ("name", "module", "type_pp", "type_hash", "sorry", "axioms", "nonstandard_axioms",
                    "deps_actual", "description", "tags", "tag_errors", "helpers")
DEST_RECORD_KEYS = ("name", "module", "type_pp", "type_hash", "sorry", "axioms", "nonstandard_axioms", "description",
                    "deps_actual")


def records_digest(payload: dict, index: list) -> str:
    """Digest of the extractor-derived content of an index: the records, problems and metadata
    that only an extraction can produce (statuses, dates and claims are recomputed on every read)."""
    import hashlib

    body = {
        "nodes": [{k: n.get(k) for k in NODE_RECORD_KEYS} for n in payload.get("nodes", [])],
        "destinations": [{k: d.get(k) for k in DEST_RECORD_KEYS} for d in payload.get("destinations", [])],
        "problems": list(payload.get("problems", [])) + list(payload.get("warnings", [])),
        "toolchain": payload.get("toolchain"),
        "nonstandard_axioms": payload.get("nonstandard_axioms"),
        "blueprint_axioms": payload.get("blueprint_axioms"),
        "fingerprints": payload.get("fingerprints"),
        "index": index,
    }
    return hashlib.sha256(json.dumps(body, sort_keys=True, ensure_ascii=False).encode()).hexdigest()


def _attest(ctx: Ctx, payload: dict, index: list, mode: str) -> None:
    """Record that an extraction on this machine produced this index content. Best effort: a
    read-only database only costs later checks their no-Lean shortcut."""
    fps = payload.get("fingerprints")
    if fps is None:
        return
    fp = json.dumps(fps, sort_keys=True)
    with Store(ctx.cfg) as st:
        if not st.readonly:
            st.attest_index(records_digest(payload, index), fp, mode, ctx.agent)


def _require_attested(cfg, data: dict, index: list) -> None:
    """Matching fingerprints prove the sources are unchanged, not that the records came from the
    extractor: trust an index only if an extraction on this machine produced exactly this content."""
    with Store(cfg) as st:
        attested = st.index_attested(records_digest(data, index))
    if not attested:
        raise NeedsFullExtract("the index records are not attested by an extraction on this machine "
                               "(edited by hand, merged, or produced elsewhere)")


def _strip_volatile(text: str) -> str:
    return "\n".join(line for line in text.splitlines() if not line.lstrip().startswith(VOLATILE_PREFIXES))


def assemble(ctx: Ctx, nodes: list[Node], dests, index: list, problems: list[str], meta: dict, *,
             fingerprints: dict | None, mode: str, claims: dict | None = None,
             blueprint_axioms: dict | None = None) -> tuple[dict, str, str, str, list[str]]:
    """Compute statuses and render the index files from extractor records.

    Shared by the full extraction, the incremental update and the no-Lean check, so that all
    three produce byte-identical files (up to the volatile lines) for the same inputs."""
    cfg = ctx.cfg
    if claims is None:
        with Store(cfg) as st:
            claims = st.claims()
    core_names = {r["name"] for r in index}
    compute(cfg, nodes, dests, core_names, claims=claims)
    # A committed introduction date is immutable.  Preserve it from the current
    # index even when a full or targeted extraction has rebuilt the Node object;
    # only new and formerly-uncommitted modules need another history scan.
    cached_dates: dict[str, str] = {}
    try:
        for rec in load_nodes_json(cfg).get("nodes", []):
            opened = rec.get("opened")
            if opened and opened != "uncommitted":
                cached_dates[rec["module"]] = opened
    except (UsageError, OSError, json.JSONDecodeError, KeyError):
        pass
    for n in nodes:
        if n.opened and n.opened != "uncommitted":
            cached_dates[n.module] = n.opened
        elif n.module in cached_dates:
            n.opened = cached_dates[n.module]
    refresh = [n.module for n in nodes if not n.opened or n.opened == "uncommitted"]
    dates = opened_dates(cfg, refresh)
    for n in nodes:
        if n.module in dates:
            n.opened = dates[n.module]
    lock = read_lock(cfg.lock_file)
    lock_problems = check_lock(lock, nodes)
    dup_problems = duplicates(nodes, index)
    payload = {
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "git_sha": head_sha(cfg),
        "extract_mode": mode,
        **meta,
        "nodes": [n.to_json() for n in nodes],
        "destinations": [d.to_json() for d in dests],
        "problems": list(problems),
        "lock_problems": lock_problems,
        "duplicate_problems": dup_problems,
    }
    if fingerprints is not None:
        payload["blueprint_axioms"] = blueprint_axioms or {}
        payload["fingerprints"] = fingerprints
    if str(cfg.get("extract", "missing_destinations", default="error")) == "warn":
        problems = [p for p in problems if not p.startswith("destination ")]
        payload["warnings"] = [p for p in payload["problems"] if p.startswith("destination ")]
        payload["problems"] = problems
    all_problems = list(problems) + lock_problems + dup_problems
    status_md = render_status_md(cfg, nodes, dests, all_problems, meta)
    nodes_text = json.dumps(payload, indent=1, ensure_ascii=False) + "\n"
    index_text = json.dumps(index, ensure_ascii=False) + "\n"
    return payload, nodes_text, status_md, index_text, all_problems


def _compare(cfg, nodes_text: str, status_md: str, index_text: str) -> list[str]:
    stale: list[str] = []
    for path, text in ((cfg.nodes_json, nodes_text), (cfg.status_md, status_md), (cfg.index_json, index_text)):
        if not path.exists() or _strip_volatile(path.read_text()) != _strip_volatile(text):
            stale.append(f"{path.relative_to(cfg.root)} is stale; run `es extract`")
    return stale


def _write(ctx: Ctx, payload: dict, index: list, nodes: list[Node], th: str,
           nodes_text: str, status_md: str, index_text: str) -> None:
    cfg = ctx.cfg
    extraction_root = cfg.root.resolve()
    primary_checkout = extraction_root == primary_root(cfg.root).resolve()
    previous: dict[str, str] = {}
    try:
        previous = {rec["name"]: rec.get("status") for rec in load_nodes_json(cfg).get("nodes", [])}
    except (UsageError, OSError, json.JSONDecodeError, KeyError):
        pass
    cfg.nodes_json.write_text(nodes_text)
    cfg.index_json.write_text(index_text)
    cfg.status_md.write_text(status_md)
    with Store(cfg) as st:
        for n in nodes:
            before = previous.get(n.name)
            if before is not None and before != n.status:
                st.event("index-status", n.name, ctx.agent,
                         {"from": before, "to": n.status, "root": str(extraction_root),
                          "primary_checkout": primary_checkout})
        records = list(index) + [
            {"name": n.name, "module": n.module, "kind": "node", "doc": n.description, "type_pp": n.type_pp} for n in nodes
        ]
        if st.search_stamp() != th:
            st.search_rebuild(records, th)


def _extract_raw(ctx: Ctx, *, th: str, mods, no_cache: bool, force: bool, budget: int | None,
                 imports: list[str] | None, memory_max: str | None, script: Path | None,
                 build_memory_max: str | None = None) -> tuple[dict, list]:
    """The extractor output for ``th``, from the cache or a fresh run (which is cached).

    ``no_cache`` skips the lookup but never empties the cache: a targeted run must not evict the
    full-environment entries, which cost a whole-library extractor run and gate every commit."""
    cfg = ctx.cfg
    with Store(cfg) as st:
        cached = None if no_cache else st.cache_get(th)
    if cached:
        return cached
    tmp = cfg.es_home / "tmp"
    tmp.mkdir(parents=True, exist_ok=True)
    out = run_extractor(cfg, out=tmp / ("nodes-raw.json" if not imports else "nodes-targeted.json"),
                        index=tmp / ("index-raw.json" if not imports else "index-targeted.json"),
                        mods=mods, force=force, budget_min=budget, imports=imports, memory_max=memory_max, script=script,
                        build_memory_max=build_memory_max,
                        retry_memory_max=cfg.extract_targeted_memory_max if imports else None)
    with Store(cfg) as st:
        st.cache_put(th, out.nodes, out.index)
        st.event("extract", None, ctx.agent, {"seconds": out.result.seconds, "peak_mib": out.result.peak_mib,
                                              "memory_max": memory_max or cfg.extract_memory_max, "tree": th[:12],
                                              "imports": imports})
    return out.nodes, out.index


def run_extract(ctx: Ctx, *, check: bool = False, no_cache: bool = False, write: bool = True, force: bool = False,
                budget: int | None = None, imports: list[str] | None = None, memory_max: str | None = None,
                script: Path | None = None, build_memory_max: str | None = None) -> tuple[dict, list, list[str]]:
    """Run (or reuse) the extractor; return (nodes payload, index, problems).

    ``build_memory_max`` caps the pre-extraction `lake build` of ``imports`` (a targeted run)."""
    from es import fingerprint

    cfg = ctx.cfg
    mods = scan_modules(cfg)
    th = fingerprint.extract_key(cfg) + ("" if not imports else "+" + ",".join(imports))
    # Only a whole-environment index can be the base of later incremental updates. Fingerprint the
    # sources before the (long) extractor run, so an edit made meanwhile shows up as stale.
    fps = None if imports else fingerprint.current(cfg, mods)
    raw, index = _extract_raw(ctx, th=th, mods=mods, no_cache=no_cache, force=force, budget=budget,
                              imports=imports, memory_max=memory_max, script=script,
                              build_memory_max=build_memory_max)
    nodes, dests, problems = nodes_from_extract(cfg, raw)
    meta = {
        "toolchain": raw.get("toolchain"), "modules": raw.get("modules"), "tree_hash": th,
        "nonstandard_axioms": sorted(set(raw.get("nonstandard_axioms", []))), "taint": raw.get("taint", {}),
    }
    payload, nodes_text, status_md, index_text, all_problems = assemble(
        ctx, nodes, dests, index, problems, meta, fingerprints=fps,
        mode="full" if not imports else "targeted " + ",".join(imports),
        blueprint_axioms=declared_blueprint_axioms(cfg, raw))
    if fps is not None:
        _attest(ctx, payload, index, "full")
    stale = _compare(cfg, nodes_text, status_md, index_text) if check else []
    if write:
        _write(ctx, payload, index, nodes, th, nodes_text, status_md, index_text)
    return payload, index, all_problems + stale


