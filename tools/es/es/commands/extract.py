STATE_DIRS = ("ESBlueprint", "ErdosSzekeres")  # overridden by config [extract] state_dirs


def state_dirs(cfg) -> list[str]:
    val = cfg.get("extract", "state_dirs")
    if val:
        return [str(x) for x in val]
    dirs = [cfg.blueprint_namespace, str(cfg.blueprint_root.relative_to(cfg.root))]
    # harness inputs that change the computed state
    for p in (cfg.root / "harness" / "config.toml", cfg.destinations_file, cfg.allowlist_file, cfg.lock_file, cfg.falsify_results_dir):
        try:
            dirs.append(str(p.relative_to(cfg.root)))
        except ValueError:
            pass
    for layer in cfg.layers():
        for p in layer.prefixes:
            dirs.append(p.replace(".", "/"))
            dirs.append(p.replace(".", "/") + ".lean")
    return sorted({d for d in dirs if (cfg.root / d).exists()})


# Lines of nodes.json / status.md that change on every extraction or commit without
# any change of state: the timestamp, the commit and tree hashes (the tree hash covers
# the commit that contains nodes.json itself), and the taint-cache counters.
VOLATILE_PREFIXES = ("Generated by", '"generated_at"', '"git_sha"', '"tree_hash"',
                     '"cached_modules"', '"scanned_constants"', '"scanned_modules"')


def _strip_volatile(text: str) -> str:
    return "\n".join(line for line in text.splitlines() if not line.lstrip().startswith(VOLATILE_PREFIXES))


def run_extract(ctx: Ctx, *, check: bool = False, no_cache: bool = False, write: bool = True, force: bool = False,
                budget: int | None = None, imports: list[str] | None = None) -> tuple[dict, list, list[str]]:
    """Run (or reuse) the extractor; return (nodes payload, index, problems)."""
    cfg = ctx.cfg
    mods = scan_modules(cfg)
    th = tree_hash(cfg, state_dirs(cfg)) + ("" if not imports else "+" + ",".join(imports))
    raw = index = None
    with Store(cfg) as st:
        claims = st.claims()
        if no_cache:
            st.cache_clear()
        else:
            cached = st.cache_get(th)
            if cached:
                raw, index = cached
        if raw is None:
            tmp = cfg.es_home / "tmp"
            tmp.mkdir(parents=True, exist_ok=True)
            out = run_extractor(cfg, out=tmp / "nodes-raw.json", index=tmp / "index-raw.json", mods=mods, force=force, budget_min=budget, imports=imports)
            raw, index = out.nodes, out.index
            st.cache_put(th, raw, index)
            st.event("extract", None, ctx.agent, {"seconds": out.result.seconds, "peak_mib": out.result.peak_mib,
                                                  "memory_max": cfg.extract_memory_max, "tree": th[:12]})
    nodes, dests, problems = nodes_from_extract(cfg, raw)
    core_names = {r["name"] for r in index}
    compute(cfg, nodes, dests, core_names, claims=claims)
    for n in nodes:
        n.opened = opened_date(cfg, n.module)
    lock = read_lock(cfg.lock_file)
    lock_problems = check_lock(lock, nodes)
    dup_problems = duplicates(nodes, index)
    meta = {
        "toolchain": raw.get("toolchain"), "modules": raw.get("modules"), "tree_hash": th,
        "nonstandard_axioms": raw.get("nonstandard_axioms", []), "taint": raw.get("taint", {}),
    }
    payload = {
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "git_sha": head_sha(cfg),
        **meta,
        "nodes": [n.to_json() for n in nodes],
        "destinations": [d.to_json() for d in dests],
        "problems": problems,
        "lock_problems": lock_problems,
        "duplicate_problems": dup_problems,
    }
    if str(cfg.get("extract", "missing_destinations", default="error")) == "warn":
        problems = [p for p in problems if not p.startswith("destination ")]
        payload["warnings"] = [p for p in payload["problems"] if p.startswith("destination ")]
        payload["problems"] = problems
    all_problems = problems + lock_problems + dup_problems
    status_md = render_status_md(cfg, nodes, dests, all_problems, meta)
    nodes_text = json.dumps(payload, indent=1, ensure_ascii=False) + "\n"
    index_text = json.dumps(index, ensure_ascii=False) + "\n"
    stale: list[str] = []
    if check:
        for path, text in ((cfg.nodes_json, nodes_text), (cfg.status_md, status_md), (cfg.index_json, index_text)):
            if not path.exists() or _strip_volatile(path.read_text()) != _strip_volatile(text):
                stale.append(f"{path.relative_to(cfg.root)} is stale; run `es extract`")
    if write:
        cfg.nodes_json.write_text(nodes_text)
        cfg.index_json.write_text(index_text)
        cfg.status_md.write_text(status_md)
        with Store(cfg) as st:
            records = list(index) + [
                {"name": n.name, "module": n.module, "kind": "node", "doc": n.description, "type_pp": n.type_pp} for n in nodes
            ]
            if st.search_stamp() != th:
                st.search_rebuild(records, th)
    return payload, index, all_problems + stale


def run(ctx: Ctx, check: bool = False, no_cache: bool = False, force: bool = False, budget: int | None = None,
        imports: list[str] | None = None) -> Result:
    payload, index, problems = run_extract(ctx, check=check, no_cache=no_cache, write=not check, force=force, budget=budget, imports=imports)
    res = Result(payload={"nodes": len(payload["nodes"]), "destinations": len(payload["destinations"]),
                          "index": len(index), "problems": problems, "taint": payload.get("taint"), "tree_hash": payload["tree_hash"]})
    res.line(f"{len(payload['nodes'])} node(s), {len(payload['destinations'])} destination(s), {len(index)} indexed declaration(s); tree {payload['tree_hash']}")
    if problems:
        res.line(f"{len(problems)} problem(s):")
        res.human.extend(f"  {p}" for p in problems)
    res.exit_code = EXIT_CHECK_FAILED if (check and problems) else EXIT_OK
    if not check:
        res.line(f"wrote {cfg_rel(ctx, ctx.cfg.nodes_json)}, {cfg_rel(ctx, ctx.cfg.index_json)}, {cfg_rel(ctx, ctx.cfg.status_md)}")
    return res


def cfg_rel(ctx: Ctx, p: Path) -> str:
    try:
        return str(p.relative_to(ctx.cfg.root))
    except ValueError:
        return str(p)


command(
    CommandSpec(
        name="extract",
        cli=["extract"],
        help="Run the Lean extractor (cached by working-tree hash), compute node status, write nodes.json/index.json/status.md.",
        run=run,
        long_running=True,
        args=[
            Arg("check", "verify committed status.md/nodes.json/index.json are current and the lock matches; write nothing", "bool"),
            Arg("no_cache", "ignore the extract cache", "bool"),
            Arg("force", "run even if another lean process is running", "bool"),
            Arg("budget", "wall-clock budget in minutes for the extractor", "int"),
            Arg("imports", "override the modules the extractor imports (partial environment; comma-separated)", "list"),
        ],
    )
)
