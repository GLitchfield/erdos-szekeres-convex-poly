def _module_of_problem(problem: str, modules: set[str], module_of_node: dict[str, str]) -> str | None:
    """The blueprint module a record-level problem belongs to (see `nodes_from_extract`)."""
    head = problem.split(":", 1)[0]
    if head in modules:
        return head
    return module_of_node.get(head)


def _merge_problems(base_problems: list[str], base_nodes: list[Node], new_problems: list[str],
                    new_nodes: list[Node], replaced: set[str], dropped: set[str], modules: list[str]) -> list[str]:
    """Rebuild the raw problem list in the order `nodes_from_extract` emits it: per module in
    sorted order, then anything unattributed, then the destination problems."""
    base_map = {n.name: n.module for n in base_nodes}
    new_map = {n.name: n.module for n in new_nodes}
    per_module: dict[str, list[str]] = {}
    other: list[str] = []
    dest: list[str] = []
    all_modules = set(modules) | set(base_map.values()) | replaced | dropped
    for p in base_problems:
        if p.startswith("destination "):
            dest.append(p)
            continue
        m = _module_of_problem(p, all_modules, base_map)
        if m is None:
            other.append(p)
        elif m not in replaced and m not in dropped:
            per_module.setdefault(m, []).append(p)
    for p in new_problems:
        if p.startswith("destination "):
            continue  # a closure-sized environment misses most destinations; keep the base's
        m = _module_of_problem(p, all_modules | replaced, new_map)
        if m in replaced:
            per_module.setdefault(m, []).append(p)
    out: list[str] = []
    for m in sorted(per_module):
        out.extend(per_module[m])
    return out + other + dest


def run_incremental(ctx: Ctx, *, write: bool = True, force: bool = False, budget: int | None = None,
                    extra_modules: list[str] | tuple[str, ...] = ()) -> tuple[dict, list, list[str]]:
    """Update nodes.json/status.md by re-extracting only the blueprint modules whose inputs
    changed (plus ``extra_modules``), carrying every other record over from the current index.

    Raises `NeedsFullExtract` when the index has no fingerprints or the core inputs changed."""
    from es import fingerprint
    from es.commands.node import (closure_olean_gib, closure_stats, elaboration_memory_max,
                                  targeted_extract_memory_max)

    cfg = ctx.cfg
    try:
        data = load_nodes_json(cfg)
    except UsageError as exc:
        raise NeedsFullExtract(str(exc)) from exc
    mods = scan_modules(cfg)
    now = fingerprint.current(cfg, mods)
    reason, stale, removed = fingerprint.diff(data.get("fingerprints"), now)
    if reason:
        raise NeedsFullExtract(reason)
    index = json.loads(cfg.index_json.read_text()) if cfg.index_json.exists() else []
    # every record not re-extracted is carried over, so the base must itself be extractor output
    _require_attested(cfg, data, index)
    stale |= {m for m in extra_modules if m in now["blueprint"]}
    base_nodes = nodes_from_json(data)
    new_nodes: list[Node] = []
    new_problems: list[str] = []
    raw_t: dict = {}
    th_tree = fingerprint.extract_key(cfg)
    if stale:
        imports = sorted(stale)
        for m in imports:
            gib = closure_olean_gib(cfg, m)
            if gib > cfg.extract_targeted_max_olean_gib:
                raise NeedsFullExtract(f"import closure of {m} holds {gib:.1f} GiB of oleans; above "
                                       f"extract.targeted_max_olean_gib = {cfg.extract_targeted_max_olean_gib}")
        closure_gib = closure_stats(cfg, imports, mods)[0]
        tmp = cfg.es_home / "tmp"
        tmp.mkdir(parents=True, exist_ok=True)
        raw_t, _ = _extract_raw(ctx, th=th_tree + "+" + ",".join(imports), mods=mods, no_cache=False, force=force,
                                budget=budget, imports=imports,
                                memory_max=targeted_extract_memory_max(cfg, closure_gib),
                                build_memory_max=elaboration_memory_max(cfg, imports, mods),
                                script=tmp / "ExtractTargeted.lean")
        extracted, _, problems_t = nodes_from_extract(cfg, raw_t)
        new_nodes = [n for n in extracted if n.module in stale]
        new_problems = problems_t
    keep = [n for n in base_nodes if n.module not in stale and n.module not in removed]
    nodes = sorted(keep + new_nodes, key=lambda n: n.module)
    base_raw_problems = list(data.get("problems", [])) + list(data.get("warnings", []))
    problems = _merge_problems(base_raw_problems, base_nodes, new_problems, new_nodes, stale, removed,
                               sorted(now["blueprint"]))
    added = stale - set(data["fingerprints"]["blueprint"])
    # The global list holds every non-standard axiom seen in the environment. A blueprint edit can
    # only remove axioms declared in the replaced or removed modules; the targeted run (current
    # sources, a sub-environment of the full one) supplies everything the new versions see.
    base_declared: dict = dict(data.get("blueprint_axioms") or {})
    obsolete = {a for m in stale | removed for a in base_declared.get(m, [])}
    axioms = sorted((set(data.get("nonstandard_axioms", [])) - obsolete) | set(raw_t.get("nonstandard_axioms", [])))
    new_declared = declared_blueprint_axioms(cfg, raw_t) if stale else {}
    blueprint_axioms = {m: v for m, v in base_declared.items() if m not in stale and m not in removed}
    blueprint_axioms.update({m: v for m, v in new_declared.items() if m in stale})
    blueprint_axioms = dict(sorted(blueprint_axioms.items()))
    meta = {
        "toolchain": data.get("toolchain"),
        "modules": (data.get("modules") or 0) + len(added) - len(removed),
        "tree_hash": th_tree,
        "nonstandard_axioms": axioms,
        "taint": raw_t.get("taint", data.get("taint", {})),
    }
    base_sha = str(data.get("git_sha") or "?")[:12]
    mode = f"incremental from {base_sha}: {len(stale)} re-extracted, {len(removed)} removed"
    dests = dests_from_json(data)
    payload, nodes_text, status_md, index_text, all_problems = assemble(
        ctx, nodes, dests, index, problems, meta, fingerprints=now, mode=mode, blueprint_axioms=blueprint_axioms)
    _attest(ctx, payload, index, "incremental")
    if write:
        _write(ctx, payload, index, nodes, th_tree, nodes_text, status_md, index_text)
        with Store(cfg) as st:
            st.event("extract-incremental", None, ctx.agent, {"reextracted": sorted(stale), "removed": sorted(removed),
                                                             "tree": th_tree[:12]})
    # reported to the caller only; not part of the written index
    return payload | {"_incremental": {"reextracted": sorted(stale), "removed": sorted(removed)}}, index, all_problems


def fast_check(ctx: Ctx) -> tuple[dict, list, list[str]]:
    """Verify the index without Lean when its fingerprints show every record is current.

    Raises `NeedsFullExtract` when only a full extraction can decide. When some blueprint modules
    changed, reports them (with the cheap fix) instead of rebuilding the whole blueprint."""
    from es import fingerprint

    cfg = ctx.cfg
    try:
        data = load_nodes_json(cfg)
    except UsageError as exc:
        raise NeedsFullExtract(str(exc)) from exc
    now = fingerprint.current(cfg)
    reason, stale, removed = fingerprint.diff(data.get("fingerprints"), now)
    if reason:
        raise NeedsFullExtract(reason)
    index = json.loads(cfg.index_json.read_text()) if cfg.index_json.exists() else []
    if stale or removed:
        changed = sorted(stale | removed)
        shown = ", ".join(changed[:6]) + (" …" if len(changed) > 6 else "")
        return data, index, [f"harness/nodes.json is stale for {len(changed)} blueprint module(s) ({shown}); "
                             "run `es extract --incremental` (re-extracts only those)"]
    _require_attested(cfg, data, index)
    nodes = nodes_from_json(data)
    meta = {k: data.get(k) for k in ("toolchain", "modules", "tree_hash", "nonstandard_axioms", "taint")}
    problems = list(data.get("problems", [])) + list(data.get("warnings", []))
    payload, nodes_text, status_md, index_text, all_problems = assemble(
        ctx, nodes, dests_from_json(data), index, problems, meta,
        fingerprints=data.get("fingerprints"), mode=str(data.get("extract_mode", "full")),
        blueprint_axioms=data.get("blueprint_axioms"))
    return payload, index, all_problems + _compare(cfg, nodes_text, status_md, index_text)


def index_inputs_changed(cfg) -> list[str]:
    """Paths under the extract state directories, the index files or the harness inputs of the
    status computation that differ from HEAD (staged, unstaged or untracked)."""
    from es.gitutil import git

    from es import fingerprint

    # Every input, whether or not it currently exists: a deleted index file or state directory is
    # a change too (git status reports it as deleted).
    files = [cfg.nodes_json, cfg.status_md, cfg.index_json, cfg.lock_file, cfg.allowlist_file,
             cfg.falsify_results_dir, cfg.extract_template, cfg.root / CONFIG_REL]
    paths = state_dirs(cfg, existing_only=False) + list(fingerprint.TOOLCHAIN_FILES)
    for p in files:
        try:
            paths.append(str(p.relative_to(cfg.root)))
        except ValueError:
            pass  # e.g. an extractor template outside the project (covered by the fingerprints)
    out = git(cfg, "status", "--porcelain", "--untracked-files=all", "--", *sorted(set(paths)), check=False)
    return [line[3:].strip() for line in out.splitlines() if line.strip()]


def run(ctx: Ctx, check: bool = False, no_cache: bool = False, force: bool = False, budget: int | None = None,
        imports: list[str] | None = None, incremental: bool = False, changed: bool = False) -> Result:
    res = Result()
    mode = "full"
    if check and changed and not imports:
        # A change that touches no index input and no index file cannot make the index stale or
        # current: the commit being checked leaves its validity exactly as HEAD had it.
        touched = index_inputs_changed(ctx.cfg)
        if not touched:
            res.payload = {"nodes": None, "problems": [], "mode": "unchanged"}
            res.line("no index input or index file differs from HEAD; nothing for this change to invalidate")
            res.exit_code = EXIT_OK
            return res
    if check and not imports and not no_cache:
        try:
            payload, index, problems = fast_check(ctx)
            mode = "fingerprint"
        except NeedsFullExtract as exc:
            res.line(f"fingerprint check unavailable ({exc}); running the full check")
            payload, index, problems = run_extract(ctx, check=True, write=False, force=force, budget=budget)
    elif incremental and not imports:
        payload, index, problems = run_incremental(ctx, force=force, budget=budget)
        mode = "incremental"
    else:
        payload, index, problems = run_extract(ctx, check=check, no_cache=no_cache, write=not check, force=force,
                                               budget=budget, imports=imports)
    res.payload = {"nodes": len(payload["nodes"]), "destinations": len(payload["destinations"]),
                   "index": len(index), "problems": problems, "taint": payload.get("taint"),
                   "tree_hash": payload.get("tree_hash"), "mode": mode}
    if mode == "incremental":
        inc = payload.get("_incremental", {})
        res.payload["reextracted"] = inc.get("reextracted", [])
        res.payload["removed"] = inc.get("removed", [])
        res.line(f"incremental update: {len(inc.get('reextracted', []))} module(s) re-extracted, "
                 f"{len(inc.get('removed', []))} removed")
    res.line(f"{len(payload['nodes'])} node(s), {len(payload['destinations'])} destination(s), {len(index)} indexed declaration(s); tree {payload.get('tree_hash')}")
    if problems:
        res.line(f"{len(problems)} problem(s):")
        res.human.extend(f"  {p}" for p in problems)
    res.exit_code = EXIT_CHECK_FAILED if (check and problems) else EXIT_OK
    if not check:
        res.line(f"wrote {cfg_rel(ctx, ctx.cfg.nodes_json)}, {cfg_rel(ctx, ctx.cfg.index_json)}, {cfg_rel(ctx, ctx.cfg.status_md)}")
    return res


def cfg_rel(ctx: Ctx, p: Path) -> str:
    try:
        return str(p.relative_to(ctx.cfg.root))
    except ValueError:
        return str(p)


