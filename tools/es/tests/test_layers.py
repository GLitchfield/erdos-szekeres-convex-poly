from es.layers import check_layers, derive_allowlists
from es.modules import scan_modules


def test_scan_and_classify(cfg):
    mods = scan_modules(cfg)
    assert mods["TCore.Chunk000"].layer == "TCerts" and mods["TCore.Chunk000"].generated
    assert mods["TCore.Basic"].layer == "TCore"
    assert mods["TBlueprint.A.Foo"].layer == "TBlueprint"
    assert mods["TCore.Consumer"].imports == ["TCore.Chunk000"]


def test_layers_pass(cfg):
    assert check_layers(cfg) == []


def test_core_importing_certificate_outside_allowlist_fails(cfg):
    (cfg.root / "TCore" / "Rogue.lean").write_text("import TCore.Chunk000\n")
    v = check_layers(cfg)
    assert any(v_.kind == "layer-allowlist" and v_.module == "TCore.Rogue" for v_ in v)


def test_certificate_importing_unlisted_core_fails(cfg):
    (cfg.root / "TCore" / "Chunk001.lean").write_text("import TCore.Basic\n")
    v = check_layers(cfg)
    assert any(v_.module == "TCore.Chunk001" and "TCore.Basic" in v_.detail for v_ in v)


def test_core_importing_blueprint_fails(cfg):
    (cfg.root / "TCore" / "Bad.lean").write_text("import TBlueprint.A.Foo\n")
    v = check_layers(cfg)
    assert any(v_.kind == "layer-order" and v_.module == "TCore.Bad" for v_ in v)


def test_root_must_import_every_node(cfg):
    (cfg.root / "TBlueprint" / "A" / "Bar.lean").write_text("theorem bar : True := by sorry\n")
    v = check_layers(cfg)
    assert any(v_.kind == "blueprint-root" and v_.module == "TBlueprint.A.Bar" for v_ in v)


def test_marker_classifies_generated(cfg):
    (cfg.root / "TCore" / "Blob.lean").write_text("-- Generated by gen.py; do not edit\nimport TCore.Encoding\n")
    mods = scan_modules(cfg)
    assert mods["TCore.Blob"].layer == "TCerts"


def test_derive_allowlists(cfg):
    d = derive_allowlists(cfg)
    assert d["harness/certificate_consumers.txt"] == ["TCore.Consumer"]
    assert d["harness/certificate_inputs.txt"] == ["TCore.Encoding"]
